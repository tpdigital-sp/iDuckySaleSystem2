const env = Object.fromEntries(
  readFileSync(new URL("../.env.local", import.meta.url), "utf8")
    .split("\n")
    .filter((l) => l.includes("=") && !l.trim().startsWith("#"))
    .map((l) => {
      const i = l.indexOf("=");
      return [l.slice(0, i).trim(), l.slice(i + 1).trim().replace(/^["']|["']$/g, "")];
    })
);
const sb = createClient(env.NEXT_PUBLIC_SUPABASE_URL, env.SUPABASE_SERVICE_ROLE_KEY, {
  auth: { persistSession: false },
});

const { data: row, error } = await sb.from("products").select("data").eq("id", "standee-frame-card").single();
if (error) throw new Error(`อ่านสินค้าไม่ได้ — ${error.message}`);
const d = structuredClone(row.data);

// ── 1) ขนาดฐาน: เหลือ 6 ซม. ขึ้นไป ────────────────────────────────────────────
const base = (d.options ?? []).find((o) => o.label === "ขนาดฐาน");
if (!base) throw new Error("ไม่มีกลุ่มขนาดฐาน — ตรวจก่อน");
if (base.extraFromQty !== 11)
  throw new Error("กลุ่มขนาดฐานยังไม่ใช่ชุด standy — รัน frame-card-standy-base.mjs ก่อน");
const dropped = base.choices.filter((c) => cmOf(c.name) < MIN_CM).map((c) => c.name);
base.choices = base.choices.filter((c) => cmOf(c.name) >= MIN_CM);
if (!base.choices.length) throw new Error("ตัดจนไม่เหลือขนาดฐาน — ตรวจก่อน");
console.log(
  dropped.length
    ? `📦 ขนาดฐาน: ตัด ${dropped.join(", ")} ออก → เหลือ ${base.choices.length} ขนาด (${base.choices[0].name} = ค่าเริ่มต้น ถึง ${base.choices.at(-1).name})`
    : `📦 ขนาดฐาน: เริ่มที่ ${base.choices[0].name} อยู่แล้ว (${base.choices.length} ขนาด) — ข้าม`
);

// ── 2) ถอดกลุ่มเลือกเฉดสีพิเศษของฐานที่ไม่มีขนาดให้ทริกแล้ว ────────────────────
const live = new Set(base.choices.map((c) => c.name));
const before = d.options.length;
d.options = d.options.filter(
  (o) => !(o.label.startsWith("เลือกสีพิเศษของฐาน (ขนาดฐาน ") && !(o.showWhen?.choices ?? []).some((c) => live.has(c)))
);
console.log(`   กลุ่มเลือกสีพิเศษของฐานที่ตายแล้ว: ถอดออก ${before - d.options.length} กลุ่ม`);

// ── 3-4) ข้อความ ─────────────────────────────────────────────────────────────
const termsWasBlank = !d.terms || d.terms.trim() === "." || d.terms.trim() === "";
d.terms = TERMS;
console.log(`   terms: ${termsWasBlank ? "กู้กลับมา" : "เขียนทับ"} ${TERMS.split("\n").length} บรรทัด`);
d.highlights = [...HIGHLIGHTS];
d.description = DESCRIPTION;

let tabHits = 0;
for (const t of d.tabs ?? []) {
  if (!t.text) continue;
  for (const [from, to] of TAB_FIXES)
    if (t.text.includes(from)) {
      t.text = t.text.replace(from, to);
      tabHits++;
    }
}
console.log(`   แท็บรายละเอียด: แทนข้อความ ${tabHits}/${TAB_FIXES.length} จุด`);

const faq = (d.seo?.faqs ?? []).find((f) => f.q.includes("ราคาเท่าไหร่"));
if (faq) faq.a = FAQ_PRICE_A;
if (d.seo?.description)
  d.seo.description = d.seo.description.replace("เลือกฐาน สกรีน 1-2 ด้าน", "เลือกฐาน 6-20 ซม. สกรีน 1-2 ด้าน");
console.log(`   FAQ ราคา: ${faq ? "แก้แล้ว" : "ไม่เจอ (ข้าม)"} · seo.description: แก้แล้ว`);

