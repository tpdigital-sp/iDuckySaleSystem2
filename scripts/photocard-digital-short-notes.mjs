const env = readFileSync(new URL("../.env.local", import.meta.url), "utf8");
const pick = (k) => (env.match(new RegExp(`^${k}=(.*)$`, "m")) || [])[1]?.trim();
const sb = createClient(pick("NEXT_PUBLIC_SUPABASE_URL"), pick("SUPABASE_SERVICE_ROLE_KEY"));

const die = (msg) => {
  console.error("✗ " + msg);
  process.exit(1);
};

const { data: rows, error } = await sb.from("products").select("*").eq("id", ID);
if (error) die(error.message);
const row = rows?.[0];
if (!row) die(`ไม่พบสินค้า id=${ID}`);
if (row.name !== EXPECT_NAME) die(`ชื่อไม่ตรงที่คาด (${row.name}) — หยุดกันเขียนทับผิดตัว`);

const d = row.data;
let changed = 0;
for (const e of EDITS) {
  const opt = (d.options ?? []).find((o) => o.label === e.label);
  if (!opt) die(`ไม่มีกลุ่ม "${e.label}"`);
  const cur = opt.note ?? "";
  if (cur === e.to) {
    console.log(`= ${e.label} — สั้นอยู่แล้ว (${cur.length})`);
    continue;
  }
  if (cur !== e.from) {
    console.log(`⚠ ${e.label} — ข้อความเดิมไม่ตรงที่คาด ข้ามให้ (มีคนแก้ทีหลัง)\n   ตอนนี้: ${cur}`);
    continue;
  }
  opt.note = e.to;
  changed++;
  console.log(`✎ ${e.label}  ${e.from.length} → ${e.to.length} ตัวอักษร\n   เดิม: ${e.from}\n   ใหม่: ${e.to}`);
}

console.log(`\n${changed} กลุ่มที่จะเปลี่ยน`);
if (WRITE && changed) {
  const { error: e2 } = await sb.from("products").update({ data: d }).eq("id", ID);
  if (e2) die(e2.message);
  console.log("✓ เขียนแล้ว");
} else if (!WRITE) {
  console.log("— ยังไม่ได้เขียน (ใส่ --write)");
}
