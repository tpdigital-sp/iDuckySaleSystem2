const FAQ_PRICE_A =
  "ราคาเริ่มต้นชิ้นละ 205 บาท (ตัว 15 ซม. + ฐาน 7 ซม. ไม่สกรีนฐาน สกรีน 1 ด้าน ที่ 500 ชิ้นขึ้นไป — " +
  "ราคาในตาราง 190 บาท + ค่าฐาน 7 ซม. 15 บาท) · สั่ง 1-10 ชิ้น ตัว 15 ซม. อยู่ที่ 280 บาท/ชิ้น " +
  "(รวมฐาน 7 ซม. และกรอบการ์ดแล้ว) — ยิ่งสั่งเยอะยิ่งถูกตามตารางราคา · ฐานใหญ่กว่า 7 ซม. คิดเพิ่มตามขนาด";

const env = Object.fromEntries(
  readFileSync(new URL("../.env.local", import.meta.url), "utf8")
    .split("\n")
    .filter((l) => l.includes("=") && !l.trim().startsWith("#"))
    .map((l) => {
      const i = l.indexOf("=");
      return [l.slice(0, i).trim(), l.slice(i + 1).trim().replace(/^["']|["']$/g, "")];
    })
);
const sb = createClient(env.NEXT_PUBLIC_SUPABASE_URL, env.SUPABASE_SERVICE_ROLE_KEY, {
  auth: { persistSession: false },
});

const { data: row, error } = await sb.from("products").select("data").eq("id", "standee-frame-card").single();
if (error) throw new Error(`อ่านสินค้าไม่ได้ — ${error.message}`);
const d = structuredClone(row.data);

// ── 1) ขนาดฐาน: เหลือ 7 ซม. ขึ้นไป + เลื่อนบันไดฝั่งปลีก ─────────────────────────
const base = (d.options ?? []).find((o) => o.label === "ขนาดฐาน");
if (!base) throw new Error("ไม่มีกลุ่มขนาดฐาน — ตรวจก่อน");
if (base.extraFromQty !== 11) throw new Error("กลุ่มขนาดฐานยังไม่ใช่ชุด standy — รันสคริปต์ก่อนหน้าก่อน");
const dropped = base.choices.filter((c) => cmOf(c.name) < MIN_CM).map((c) => c.name);
base.choices = base.choices.filter((c) => cmOf(c.name) >= MIN_CM);
if (!base.choices.length) throw new Error("ตัดจนไม่เหลือขนาดฐาน — ตรวจก่อน");
for (const c of base.choices) {
  const below = (cmOf(c.name) - MIN_CM) * STEP; // ตัวเล็กสุด = รวมในราคาปลีกแล้ว
  if (below > 0) c.extraBelow = below;
  else delete c.extraBelow;
}
console.log(
  `📦 ขนาดฐาน: ${dropped.length ? `ตัด ${dropped.join(", ")} ออก → ` : ""}เหลือ ${base.choices.length} ขนาด (${base.choices[0].name} = ค่าเริ่มต้น ถึง ${base.choices.at(-1).name})`
);
console.log(
  "   ค่าฐาน/ชิ้น — " +
    base.choices.map((c) => `${c.name}: ปลีก ${c.extraBelow ?? 0} · ส่ง ${c.extra ?? 0}`).join(" | ")
);

// ── 2) ถอดกลุ่มเลือกเฉดสีพิเศษของฐานที่ไม่มีขนาดให้ทริกแล้ว ────────────────────
const live = new Set(base.choices.map((c) => c.name));
const before = d.options.length;
d.options = d.options.filter(
  (o) => !(o.label.startsWith("เลือกสีพิเศษของฐาน (ขนาดฐาน ") && !(o.showWhen?.choices ?? []).some((c) => live.has(c)))
);
console.log(`   กลุ่มเลือกสีพิเศษของฐานที่ตายแล้ว: ถอดออก ${before - d.options.length} กลุ่ม`);

// ── 3) ข้อความ ───────────────────────────────────────────────────────────────
d.terms = TERMS;
d.highlights = [...HIGHLIGHTS];
d.description = DESCRIPTION;
let tabHits = 0;
for (const t of d.tabs ?? []) {
  if (!t.text) continue;
  for (const [from, to] of TAB_FIXES)
    if (t.text.includes(from)) {
      t.text = t.text.replaceAll(from, to);
      tabHits++;
    }
}
const faq = (d.seo?.faqs ?? []).find((f) => f.q.includes("ราคาเท่าไหร่"));
if (faq) faq.a = FAQ_PRICE_A;
if (d.seo?.description) d.seo.description = d.seo.description.replace("เลือกฐาน 6-20 ซม.", "เลือกฐาน 7-20 ซม.");
console.log(`   ข้อความ: terms ${TERMS.split("\n").length} บรรทัด · แท็บ ${tabHits}/${TAB_FIXES.length} จุด · FAQ ${faq ? "แก้แล้ว" : "ไม่เจอ"}`);
if (JSON.stringify(d).includes("ฐาน 6 ซม."))
  throw new Error('ยังมีข้อความ "ฐาน 6 ซม." ตกค้าง — ตรวจก่อน');

// ── ช่วงราคา + เงาตาราง (เรทที่ 1 เก็บ 2 ที่ ต้องตรงกันเสมอ) ────────────────────
const r1 = (d.priceRates ?? []).find((r) => r.id === "r1");
if (!r1 || JSON.stringify(r1.pricing) !== JSON.stringify(d.pricing))
  throw new Error("data.pricing กับ priceRates[0].pricing ไม่ตรงกัน — ตรวจก่อน");
{
  const all = d.priceRates.flatMap((r) => Object.values(r.pricing.cells).flat()).filter((n) => n > 0);
  d.priceMin = Math.min(...all);
  d.priceMax = Math.max(...all);
  d.price = d.priceMin;
}
d.savedAt = new Date().toISOString();
console.log(`   ช่วงราคาในตาราง: ฿${d.priceMin} – ฿${d.priceMax} (ยังไม่รวมค่าฐาน) · รวมกลุ่มตัวเลือก ${d.options.length}`);

if (!WRITE) {
  console.log("\n(ยังไม่บันทึก — ใส่ --write)");
  process.exit(0);
}
const up = await sb.from("products").update({ data: d, price: d.price }).eq("id", "standee-frame-card");
if (up.error) throw new Error(`บันทึกไม่สำเร็จ — ${up.error.message}`);
const { data: back } = await sb.from("products").select("data").eq("id", "standee-frame-card").single();
const got = back.data;
const gotBase = got.options.find((o) => o.label === "ขนาดฐาน")?.choices ?? [];
if (!gotBase.every((c) => cmOf(c.name) >= MIN_CM) || gotBase[0]?.extraBelow || got.terms !== TERMS || got.savedAt !== d.savedAt)
  throw new Error("อ่านกลับมาแล้วค่าไม่ตรงที่เขียน — ตรวจก่อน");
console.log("✅ บันทึก standee-frame-card แล้ว (อ่านกลับมาเทียบผ่าน)");
