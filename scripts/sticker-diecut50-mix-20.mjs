import { createClient } from "@supabase/supabase-js";

const WRITE = process.argv.includes("--write");
const env = readFileSync(new URL("../.env.local", import.meta.url), "utf8");
const pick = (k) => (env.match(new RegExp(`^${k}=(.*)$`, "m")) || [])[1]?.trim();
const sb = createClient(pick("NEXT_PUBLIC_SUPABASE_URL"), pick("SUPABASE_SERVICE_ROLE_KEY"));

const MIX_50 = { baseFee: 20, includedDesigns: 2, extraFee: 20 };

const die = (msg) => {
  console.error("✗ " + msg);
  process.exit(1);
};

/**
 * แทนข้อความคู่ from→to ในทุกที่ที่ข้อความอยู่ (terms + ทุกแท็บ + คำตอบ FAQ)
 * - เจอ to อยู่แล้ว = รอบก่อนแทนไปแล้ว → นับว่าผ่าน (รันซ้ำได้)
 * - ทั้งสินค้าไม่เจอทั้ง from และ to สักคู่ = โครงสร้างข้อความเปลี่ยน → หยุดก่อน กันแทนผิดที่
 */
function applySwaps(id, d, swaps) {
  for (const [from, to] of swaps) {
    let hit = false;
    const sub = (t) => {
      if (!t) return t;
      if (t.includes(to)) { hit = true; return t; }
      if (!t.includes(from)) return t;
      hit = true;
      return t.replaceAll(from, to);
    };
    d.terms = sub(d.terms);
    for (const tab of d.tabs ?? []) tab.text = sub(tab.text);
    for (const f of d.seo?.faqs ?? []) f.a = sub(f.a);
    if (!hit) die(`${id}: ไม่พบข้อความ "${from.slice(0, 70)}…" (ทั้งแบบเก่าและแบบใหม่)`);
  }
}

