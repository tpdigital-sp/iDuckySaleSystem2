for (const job of JOBS) {
  const { data: rows, error } = await sb.from("products").select("*").eq("id", job.id);
  if (error) die(error.message);
  const row = rows?.[0];
  if (!row) die(`ไม่พบสินค้า id=${job.id}`);
  if (row.name !== job.expectName) die(`${job.id}: ชื่อไม่ตรงที่คาด (${row.name})`);
  const d = row.data;

  // หา "ตัวเลือกไดคัท 50%" ในกลุ่มแบบไดคัท — ต้องเจอตัวเดียวเป๊ะ
  const want = job.choice50 ?? "ไดคัท 50%";
  const hits = [];
  for (const o of d.options ?? [])
    for (const c of o.choices ?? []) if (c.name === want) hits.push({ group: o.label, choice: c });
  if (hits.length !== 1) die(`${job.id}: เจอตัวเลือก "${want}" ${hits.length} ที่ (ต้องเจอ 1)`);
  const { group, choice } = hits[0];
  if (group !== "แบบไดคัท") die(`${job.id}: ตัวเลือกอยู่กลุ่ม "${group}" ไม่ใช่ "แบบไดคัท" — เช็คก่อน`);

  const before = JSON.stringify(choice.mixRule);
  choice.mixRule = { ...MIX_50 };
  applySwaps(job.id, d, job.swaps);
  d.savedAt = new Date().toISOString();

  console.log(`${job.id}: [${group}] "${choice.name}" mixRule ${before ?? "—"} → ${JSON.stringify(choice.mixRule)}`);
  console.log(`   (กติกากลางของสินค้า — ใช้กับไดคัท 100%: ${JSON.stringify(d.mixRule)})`);
  if (!WRITE) continue;
  const { error: e2 } = await sb.from("products").update({ data: d }).eq("id", job.id);
  if (e2) die(`${job.id}: ${e2.message}`);
  console.log(`   ✓ เขียนแล้ว`);
}
