/** รายการที่ของยังไม่ถึงโต๊ะแพ็ค (สรุปจาก OrderItem.arrival) */
export interface PackMissing {
  /** ตำแหน่งรายการใน order.items */
  index: number;
  item: string;
  status: Exclude<PackArrivalStatus, "มาครบ">;
  /** มาแล้วกี่ชิ้น (มาไม่ครบ) */
  got?: number;
  /** ต้องได้กี่ชิ้น (= qty ของรายการ) */
  need: number;
  expectedAt?: string;
  note?: string;
  by: string;
  at: string;
  /** ปักครั้งแรกเมื่อไหร่ */
  since: string;
}

/** รายการที่ของยังไม่มา/ไม่ครบของออเดอร์นี้ (ว่าง = ของครบทุกรายการหรือไม่เคยปัก) */
export function packMissingOf(order: Order): PackMissing[] {
  const out: PackMissing[] = [];
  order.items.forEach((it, i) => {
    const a = it.arrival;
    if (!a || a.status === "มาครบ") return;
    out.push({
      index: i,
      item: it.name,
      status: a.status,
      got: a.status === "มาไม่ครบ" ? a.got ?? 0 : undefined,
      need: it.qty,
      expectedAt: a.expectedAt,
      note: a.note,
      by: a.by,
      at: a.at,
      since: a.since ?? a.at,
    });
  });
  return out;
}

/** ของที่คาดว่าจะมา "เลยวันที่คาดแล้ว" หรือยัง (ไม่ได้ระบุวัน = ไม่เลย) */
export function arrivalOverdue(expectedAt?: string): boolean {
  if (!expectedAt) return false;
  const d = new Date(expectedAt + "T00:00:00");
  if (Number.isNaN(d.getTime())) return false;
  const today = new Date();
  today.setHours(0, 0, 0, 0);
  return d.getTime() < today.getTime();
}

/** รอของมากี่วันแล้ว นับจากวันที่ปักครั้งแรก (0 = วันนี้) */
export function waitingDays(since?: string): number {
  if (!since) return 0;
  const d = new Date(since);
  if (Number.isNaN(d.getTime())) return 0;
  d.setHours(0, 0, 0, 0);
  const today = new Date();
  today.setHours(0, 0, 0, 0);
  return Math.max(0, Math.round((today.getTime() - d.getTime()) / 86400000));
}

/** วันที่ YYYY-MM-DD → "12 ก.ย. 69" (พ.ศ. ตามที่ทีมคุยกัน) */
export function fmtExpected(ymd?: string): string {
  if (!ymd) return "";
  const d = new Date(ymd + "T00:00:00");
  if (Number.isNaN(d.getTime())) return ymd;
  return d.toLocaleDateString("th-TH", { day: "numeric", month: "short", year: "2-digit" });
}

/** ข้อความสรุปสถานะของบรรทัดเดียว — ใช้ในลิสต์/ป้าย ให้ทุกจอพูดเหมือนกัน */
export function arrivalSummary(a: Pick<PackArrival, "status" | "got">, need: number, unit = "ชิ้น"): string {
  if (a.status === "มาครบ") return "มาครบแล้ว";
  if (a.status === "มาไม่ครบ") return `มาแล้ว ${a.got ?? 0}/${need} ${unit}`;
  return "ยังไม่มา";
}

export type ArrivalPatch = { status: PackArrivalStatus; got?: number; expectedAt?: string; note?: string };

/**
 * 📦 ปักสถานะของรายการ (ยังไม่มา / มาไม่ครบ / มาครบ) + ลงประวัติ — คืน Order ใหม่ ไม่แก้ของเดิม
 * ใช้ทั้งโหมดแพ็คในหน้าออเดอร์และโมดัลที่สถานีแพ็ค–ส่ง จะได้ลง log/นับวันเหมือนกัน
 * since = วันที่ปักครั้งแรกในรอบนี้ (แก้หมายเหตุ/วันคาดไม่รีเซ็ต · มาครบแล้วปักใหม่ = เริ่มนับใหม่)
 * "มาครบ" เก็บไว้เป็นประวัติว่าเคยรอ (ไม่ลบ arrival ทิ้ง) แต่ไม่ติดด่านแล้ว
 */
export function applyArrival(order: Order, itemIndex: number, patch: ArrivalPatch, actor: string): Order {
  const item = order.items[itemIndex];
  if (!item) return order;
  const prev = item.arrival;
  const now = new Date().toISOString();
  const wasMissing = !!prev && prev.status !== "มาครบ";
  const done = patch.status === "มาครบ";
  const arrival: PackArrival = {
    status: patch.status,
    ...(patch.status === "มาไม่ครบ" ? { got: patch.got ?? 0 } : {}),
    ...(!done && patch.expectedAt ? { expectedAt: patch.expectedAt } : {}),
    ...(!done && patch.note ? { note: patch.note } : {}),
    by: actor,
    at: now,
    ...(!done ? { since: wasMissing ? prev!.since ?? prev!.at : now } : {}),
  };
  const items = order.items.map((it, i) => (i === itemIndex ? { ...it, arrival } : it));
  const detail = [
    item.name,
    patch.status === "มาไม่ครบ" ? `มาแล้ว ${patch.got ?? 0}/${item.qty}` : "",
    !done && patch.expectedAt ? `คาดว่ามา ${fmtExpected(patch.expectedAt)}` : "",
    !done && patch.note ? patch.note : "",
    done && wasMissing ? `รอมา ${waitingDays(prev!.since ?? prev!.at)} วัน` : "",
  ]
    .filter(Boolean)
    .join(" — ");
  return withLog(
    { ...order, items },
    actor,
    done ? "📦 ของมาครบแล้ว" : patch.status === "ยังไม่มา" ? "📦 ของยังไม่มา" : "📦 ของมาไม่ครบ",
    detail
  );
}

/**
 * ตรวจว่าออเดอร์ผ่านขั้นตอนแพ็คครบหรือยัง
 * ใช้ทั้งหน้าออเดอร์ (แสดงความคืบหน้า) และหน้ายิงเลขพัสดุ (บล็อกไม่ให้ยิง)
 */
/** คีย์รูปแบบงาน "item:proof" ไว้จับคู่ระหว่างที่เลือกส่ง/ที่ส่งไปแล้ว */
export function proofKey(item: number, proof: number): string {
  return `${item}:${proof}`;
}

/** ตำแหน่งรูปจริงของรายการในรอบส่ง/แผน — จับคู่ด้วย url ก่อน (กราฟฟิกลบ/สลับรูปทีหลังตำแหน่งเปลี่ยน) ไม่มี url ค่อยใช้ตำแหน่ง */
function resolveProofKey(order: Order, sp: Shipment["proofs"][number]): string | null {
  const it = order.items[sp.item];
  if (!it) return null;
  const proofs = proofsOf(it);
  let j = sp.url ? proofs.findIndex((p) => p.url === sp.url) : -1;
  if (j < 0) j = sp.proof;
  if (j < 0 || j >= proofs.length) return null;
  return proofKey(sp.item, j);
}

/** จำนวนชิ้นของรูปแบบงาน 1 รูป สำหรับคิดแบ่งส่ง — รูปที่ไม่มีป้ายจำนวน นับเป็น 1 หน่วย "ทั้งรูป" (แบ่งจำนวนไม่ได้) */
export function proofSplitTotal(p: Proof): number {
  const n = Math.floor(p.qty ?? 0);
  return n > 0 ? n : 1;
}

/**
 * 🚚 สถานะแบ่งส่งของรูปแบบงาน 1 รูป — ส่งไปแล้วกี่ชิ้น เหลือกี่ชิ้น
 * (พนักงานขอ 14 ก.ย. 69: "ลายนี้แบ่งส่งไปก่อน 1 ชิ้น" — เดิมแบ่งได้ทีละทั้งรูป)
 */
export interface ProofShipState {
  /** จำนวนทั้งหมดของรูปนี้ (รูปไม่มีป้ายจำนวน = 1 หน่วย) */
  total: number;
  /** รูปนี้มีป้ายจำนวนจริง = ระบุจำนวนที่ส่งก่อนได้ */
  labeled: boolean;
  shipped: number;
  remaining: number;
  /** รอบแบ่งส่งที่รูปนี้เคยออกไป (1-based) */
  rounds: number[];
}

export function proofShipStates(order: Order): Map<string, ProofShipState> {
  const out = new Map<string, ProofShipState>();
  order.items.forEach((it, i) =>
    proofsOf(it).forEach((p, j) => {
      const total = proofSplitTotal(p);
      out.set(proofKey(i, j), { total, labeled: (p.qty ?? 0) > 0, shipped: 0, remaining: total, rounds: [] });
    })
  );
  (order.shipments ?? []).forEach((s, n) => {
    s.proofs.forEach((sp) => {
      const k = resolveProofKey(order, sp);
      const st = k ? out.get(k) : undefined;
      if (!st) return;
      // รอบเก่าเก็บจำนวนเต็มของรูปไว้ = ออกไปทั้งรูป · รอบใหม่เก็บเฉพาะจำนวนที่ไปรอบนั้น
      const q = sp.qty && sp.qty > 0 ? Math.min(Math.floor(sp.qty), st.total) : st.total;
      st.shipped = Math.min(st.total, st.shipped + q);
      st.remaining = Math.max(0, st.total - st.shipped);
      if (!st.rounds.includes(n + 1)) st.rounds.push(n + 1);
    });
  });
  return out;
}

/** คีย์รูป → จำนวนชิ้นที่ไปกับรอบส่ง/แผน 1 รอบ (ไม่ระบุจำนวน = ทั้งรูป) */
export function roundSel(order: Order, proofs: Shipment["proofs"]): Map<string, number> {
  const states = proofShipStates(order);
  const out = new Map<string, number>();
  proofs.forEach((sp) => {
    const k = resolveProofKey(order, sp);
    if (!k) return;
    const total = states.get(k)?.total ?? 1;
    const q = sp.qty && sp.qty > 0 ? Math.min(Math.floor(sp.qty), total) : total;
    out.set(k, (out.get(k) ?? 0) + q);
  });
  return out;
}

/**
 * 🚚 รูปแบบงานที่ส่งออกไปแล้ว → คีย์ "item:proof" → รอบล่าสุดที่ออกไป (1-based)
 * ⚠️ รูปที่ออกไปแค่บางส่วนก็อยู่ในนี้ — ดู proofShipStates ต่อว่าเหลืออีกกี่ชิ้น
 */
export function shippedProofRounds(order: Order): Map<string, number> {
  const out = new Map<string, number>();
  proofShipStates(order).forEach((st, k) => {
    if (st.rounds.length) out.set(k, st.rounds[st.rounds.length - 1]);
  });
  return out;
}

/** 📋 รูปที่อยู่ในแผนแบ่งส่ง → คีย์ "item:proof" → รอบตามแผน (1-based) · จับคู่ url ก่อนเหมือน shippedProofRounds */
export function plannedProofRounds(order: Order): Map<string, number> {
  const out = new Map<string, number>();
  (order.shipPlan ?? []).forEach((r, n) => {
    r.proofs.forEach((sp) => {
      const k = resolveProofKey(order, sp);
      if (k) out.set(k, n + 1);
    });
  });
  return out;
}

/** 📋 จำนวนชิ้นที่แผนสั่งให้ส่งในรอบหนึ่ง → คีย์รูป → จำนวน (ไว้โชว์ป้าย "ส่งก่อน 1/10 ชิ้น") */
export function plannedRoundQty(order: Order, index: number): Map<string, number> {
  const r = (order.shipPlan ?? [])[index];
  return r ? roundSel(order, r.proofs) : new Map();
}

/**
 * 📋 รอบถัดไปตามแผนที่ยังส่งไม่ครบ (คีย์รูป + จำนวนที่ยังต้องส่งรอบนี้) — null = ไม่มีแผน หรือส่งตามแผนครบแล้ว (เหลือแค่รอบสุดท้าย)
 * ฝ่ายแพ็คเห็นรูปพวกนี้ติดป้าย "ส่งก่อน" พร้อมจำนวน และปุ่มส่งบางส่วนล็อกไว้ที่ชุดนี้ ไม่ต้องเลือกเอง
 */
export function nextPlannedRound(order: Order): { index: number; round: ShipPlanRound; keys: string[]; qty: Map<string, number> } | null {
  const rounds = order.shipPlan ?? [];
  if (!rounds.length) return null;
  const states = proofShipStates(order);
  const want = new Map<string, number>(); // จำนวนสะสมที่แผนสั่งให้ส่งถึงรอบนี้
  for (let n = 0; n < rounds.length; n++) {
    roundSel(order, rounds[n].proofs).forEach((q, k) => want.set(k, (want.get(k) ?? 0) + q));
    const pending = new Map<string, number>();
    want.forEach((q, k) => {
      const st = states.get(k);
      if (!st) return;
      const left = Math.min(q, st.total) - st.shipped;
      if (left > 0) pending.set(k, Math.min(left, st.remaining));
    });
    if (pending.size) return { index: n, round: rounds[n], keys: [...pending.keys()], qty: pending };
  }
  return null;
}

/** จำนวนชิ้น (ตามป้ายบนรูป) ที่ไปกับรอบแบ่งส่งรอบหนึ่ง */
export function shipmentQty(s: Shipment): number {
  return s.proofs.reduce((n, p) => n + (p.qty ?? 0), 0);
}

/** สรุปแบ่งส่งของใบ: ส่งไปแล้วกี่รอบ กี่ชิ้น จากทั้งหมดกี่ชิ้น (นับจากป้ายบนรูปแบบงาน) · null = ไม่เคยแบ่งส่ง */
export function partialShipSummary(order: Order): { rounds: number; shipped: number; total: number; proofsShipped: number; proofsTotal: number } | null {
  const ships = order.shipments ?? [];
  if (!ships.length) return null;
  const states = proofShipStates(order);
  let total = 0;
  let proofsTotal = 0;
  order.items.forEach((it) => proofsOf(it).forEach((p) => {
    total += p.qty ?? 0;
    proofsTotal += 1;
  }));
  return {
    rounds: ships.length,
    shipped: ships.reduce((n, s) => n + shipmentQty(s), 0),
    total,
    // นับเฉพาะรูปที่ออกไปครบแล้ว — รูปที่แบ่งส่งไปบางส่วนยังค้างรอบถัดไป
    proofsShipped: [...states.values()].filter((st) => st.rounds.length > 0 && st.remaining <= 0).length,
    proofsTotal,
  };
}

/**
 * 📋 รอบตามแผนแบ่งส่งที่ "ยังไม่ได้ส่ง และไม่ใช่รอบสุดท้าย" → ห้ามปิดทั้งใบจนกว่าจะส่งรอบนี้ทางปุ่มส่งบางส่วน
 * รอบตามแผนที่เอาของที่เหลือไปทั้งหมด = รอบสุดท้าย (partialGate ให้ไปปิดใบทางปกติ) จึงไม่นับ · ใบปิดไปแล้วไม่นับ
 */
export function pendingPlanRound(order: Order): { round: number; qty: number } | null {
  if ((order.tracking ?? "").trim() || order.packedAt) return null;
  const next = nextPlannedRound(order);
  if (!next) return null;
  let qty = 0;
  next.qty.forEach((q) => (qty += q));
  let remaining = 0;
  proofShipStates(order).forEach((st) => (remaining += st.remaining));
  if (qty <= 0 || qty >= remaining) return null;
  return { round: (order.shipments?.length ?? 0) + 1, qty };
}

/** ใบที่ส่งไปแล้วบางส่วนแต่ยังไม่ปิด (ยังไม่ยิงเลขรอบสุดท้าย) */
export function isPartiallyShipped(order: Order): boolean {
  // 🏪 ใบมารับเองไม่มีเลขพัสดุ — ปิดใบด้วย packedAt (กดแพ็คเสร็จรอบสุดท้าย)
  return (order.shipments?.length ?? 0) > 0 && !(order.tracking ?? "").trim() && !order.packedAt;
}

/**
 * โฟลเดอร์ผลิตที่เป็น "งานตัวอย่าง" — กติกาเจ้าของร้าน 16 ก.ย. 69: ชื่อโฟลเดอร์ต้องมีป้ายวงเล็บที่ลงท้ายด้วย "ตย"
 * ผ่าน: "(ตย)" "(เร่งขึ้นตย)" "(ขึ้นตย)" · ไม่ผ่าน: "(ขึ้นตยแล้ว)" (= ตัวอย่างผ่านแล้ว นี่คือโฟลเดอร์งานจริง) "(ids)"
 */
export const SAMPLE_FOLDER_RE = /\([^()]*ตย\s*\)/u;
export const isSampleFolderName = (name: string) => SAMPLE_FOLDER_RE.test(String(name ?? "").normalize("NFC"));

/**
 * 🎁➗ รอบตัวอย่างของใบมัดจำ 50% (กติกาเจ้าของร้าน 16 ก.ย. 69 · OD-260911-8026 ลูกค้าโอนมัดจำแล้วขอดูชิ้นงานจริงก่อนผลิตล็อตหลัก)
 * กฎ "พิมพ์ใบปะหน้า/ยิงเลขไม่ได้จนครบ 100%" มีไว้กันของหลักออกไปทั้งที่ยังเก็บเงินไม่ครบ
 * → ถ้าใบนี้ (1) มัดจำงวดแรกเข้าแล้ว ยังไม่ครบ (2) กราฟฟิกติ๊ก 🎁 มีชิ้นงานตัวอย่างของจริง
 *   (3) โยนโฟลเดอร์ผลิตชื่อ "(เร่งขึ้นตย)" แล้ว = ร้านตั้งใจส่งตัวอย่างก่อน
 *   ให้พิมพ์ใบปะหน้า + ส่งบางส่วน "รอบที่ไม่ใช่รอบสุดท้าย" ได้ · รอบสุดท้าย/ช่องเลขพัสดุปกติยังล็อกครบ 100% เหมือนเดิม
 * คืน null = ไม่เข้าเกณฑ์ · missing = สัญญาณที่ยังขาด (ไว้บอกคนหน้างานว่าต้องติ๊ก/โยนอะไร)
 */
export function depositSampleRun(order: Order): { ok: boolean; missing: string[]; printed?: { by: string; at: string } } | null {
  const d = order.deposit;
  if (!d?.firstPaidAt || d.settledAt) return null;
  if ((order.tracking ?? "").trim()) return null;
  const missing: string[] = [];
  if (!order.items.some((it) => it.sampleRequired)) missing.push("กราฟฟิกยังไม่ติ๊ก 🎁 มีชิ้นงานตัวอย่าง (ของจริง)");
  // โฟลเดอร์ตัวอย่างรู้ได้ 2 ทาง: ติ๊กส่งผลิตด้วยโฟลเดอร์ (…ตย) หรือแผนแบ่งส่งรอบที่ยังไม่ออกถูกสร้างจากโฟลเดอร์ (…ตย) (โยนโฟลเดอร์ → อ่านชื่อไฟล์ jpg)
  const sent = (order.shipments ?? []).length;
  const planFromSample = (order.shipPlan ?? []).some((r, n) => n >= sent && !!r.sampleFolder && isSampleFolderName(r.sampleFolder));
  if (!isSampleFolderName(order.productionSent?.folder ?? "") && !planFromSample) missing.push('ยังไม่โยนโฟลเดอร์ผลิตที่ชื่อมี "(…ตย)" เช่น (เร่งขึ้นตย)');
  // ✅ รอบตัวอย่างที่จะออก (รอบถัดไปของแผน) ต้องมีเจ้าของร้านอนุมัติ — แอดมิน/กราฟฟิก/แพ็คตั้งเองไม่ได้
  const pending = pendingSampleRound(order);
  // รอบตัวอย่างออกไปแล้วและไม่มีรอบตัวอย่างต่อ = ที่เหลือคือล็อตหลัก → ล็อกกลับจนกว่ายอดคงเหลือครบ (เจ้าของร้านถาม 16 ก.ย. 69)
  if (!pending && sent > 0) missing.push("ส่งรอบตัวอย่างไปแล้ว — ที่เหลือคือล็อตหลัก ต้องเก็บยอดคงเหลือครบก่อน");
  else if (!pending) missing.push("แอดมินยังไม่ระบุแผนแบ่งส่งรอบตัวอย่าง (📋 ระบุของที่ส่งก่อน)");
  else if (!pending.round.sampleApproved) missing.push("รอเจ้าของร้านกด ✅ อนุมัติส่งตัวอย่างก่อนเก็บยอดคงเหลือ (ในกล่อง 📋 แผนแบ่งส่ง)");
  const printed = pending?.round.samplePrintedAt;
  return { ok: missing.length === 0, missing, ...(printed ? { printed } : {}) };
}

/** ใบปะหน้ารอบตัวอย่างพิมพ์ได้ไหม — ครบเงื่อนไข (depositSampleRun) และยังไม่เคยพิมพ์ (พิมพ์ได้ครั้งเดียว ล็อกกลับทันที) */
export function sampleLabelOk(order: Order): boolean {
  const r = depositSampleRun(order);
  return !!r && r.ok && !r.printed;
}

/** รอบแบ่งส่งรอบถัดไปที่ยังไม่ออก (รอบตัวอย่างของใบมัดจำ) — index ในแผน + ตัวรอบ · null = ไม่มีแผนค้าง */
export function pendingSampleRound(order: Order): { index: number; round: ShipPlanRound } | null {
  const sent = (order.shipments ?? []).length;
  const round = order.shipPlan?.[sent];
  return round ? { index: sent, round } : null;
}

/** ใบมัดจำที่เข้าเกณฑ์ส่งตัวอย่างก่อน (ดู depositSampleRun) — ใช้ปลดล็อกใบปะหน้า/ด่านแบ่งส่งรอบที่ไม่ใช่รอบสุดท้าย */
export function isDepositSampleRun(order: Order): boolean {
  return depositSampleRun(order)?.ok === true;
}

/** ด่านตรวจก่อน "ส่งบางส่วน" — ตรวจเฉพาะรูปที่เลือกไปรอบนี้ + รายการที่รูปนั้นอยู่ (ไม่บังคับงานตัวอย่าง/ใบกำกับ/ของครบทั้งใบ = ไปกับรอบสุดท้าย) */
export interface PartialGate {
  ready: boolean;
  /** เหตุผลที่ยังส่งรอบนี้ไม่ได้ (ไว้โชว์/ลง log) */
  reasons: string[];
  /** เป็นรอบที่เอาของที่เหลือไปทั้งหมด = ต้องยิงเป็นรอบสุดท้ายแทน */
  isLastRound: boolean;
  /**
   * 🚨 ของที่เหลือ (ที่ไม่ได้ไปรอบนี้) นับครบ+ของมาครบอยู่แล้ว และแอดมินไม่ได้สั่งแบ่งส่ง
   * = เกือบทุกครั้งคือคนแพ็คส่งทั้งใบกล่องเดียวแต่กดผิดมาทางแบ่งส่ง (ดูเหตุผลข้อสุดท้ายใน reasons)
   */
  looksWhole: boolean;
}

/** ขึ้นต้นเหตุผล "ของที่เหลือพร้อมส่งอยู่แล้ว" — หน้าจอใช้คัดบรรทัดนี้ออกจากลิสต์ แล้วโชว์เป็นกล่องเตือนใหญ่แทน */
export const SPLIT_WHOLE_HINT = "ของที่เหลือนับครบพร้อมส่งอยู่แล้ว";

/** สิ่งที่เลือกไปรอบนี้: คีย์รูปเฉย ๆ = ทั้งที่เหลือของรูปนั้น · คู่ [คีย์, จำนวน] = แบ่งเฉพาะจำนวนนั้น */
export type PartialSel = Map<string, number> | Iterable<string> | Iterable<readonly [string, number]>;

/** แปลงสิ่งที่เลือก → คีย์รูป → จำนวนชิ้นที่จะส่งรอบนี้ */
export function partialSelMap(order: Order, sel: PartialSel): Map<string, number> {
  const states = proofShipStates(order);
  const out = new Map<string, number>();
  const add = (k: string, q?: number) => {
    const st = states.get(k);
    const want = q && q > 0 ? Math.floor(q) : st?.remaining ?? 0;
    if (want > 0) out.set(k, (out.get(k) ?? 0) + want);
  };
  if (sel instanceof Map) sel.forEach((q, k) => add(k, q));
  else
    for (const e of sel as Iterable<string | readonly [string, number]>) {
      if (typeof e === "string") add(e);
      else add(e[0], e[1]);
    }
  return out;
}

export function partialGate(order: Order, sel: PartialSel): PartialGate {
  const want = partialSelMap(order, sel);
  const states = proofShipStates(order);
  const reasons: string[] = [];
  if (!want.size) reasons.push("ยังไม่ได้เลือกรูปที่จะส่งรอบนี้");
  const uncounted: string[] = [];
  const short: string[] = [];
  const over: string[] = [];
  const sentOut: string[] = [];
  const unread = new Set<string>();
  /** ของที่ "ไม่ได้ไปรอบนี้" แต่นับครบ + ของมาครบแล้ว = พร้อมส่งอยู่แล้ว (ไม่มีเหตุให้ค้างไว้รอบหน้า) */
  const leftReady: string[] = [];
  /** มีของที่ยังไม่พร้อม (ยังไม่ได้นับ/นับไม่ครบ/ของยังไม่มา) ค้างอยู่ = แบ่งส่งสมเหตุผล */
  let leftWaiting = false;
  let remaining = 0;
  let selQty = 0;
  order.items.forEach((it, i) => {
    const itemWaiting = !!it.arrival && it.arrival.status !== "มาครบ";
    proofsOf(it).forEach((p, j) => {
      const k = proofKey(i, j);
      const st = states.get(k) ?? { total: proofSplitTotal(p), labeled: false, shipped: 0, remaining: proofSplitTotal(p), rounds: [] };
      remaining += st.remaining;
      const q = want.get(k) ?? 0;
      const label = `${it.name} รูปที่ ${j + 1}`;
      const leftAfter = Math.max(0, st.remaining - Math.min(q, st.remaining));
      if (leftAfter > 0) {
        if (!itemWaiting && p.pack?.status === "ครบ") leftReady.push(`${label} ${leftAfter.toLocaleString("th-TH")} ${proofUnit(p)}`);
        else leftWaiting = true;
      }
      if (!q) return;
      const go = Math.min(q, st.remaining);
      selQty += go;
      if (st.remaining <= 0) sentOut.push(label);
      else if (q > st.remaining) over.push(`${label} (เลือก ${q} เหลือ ${st.remaining})`);
      if (!p.pack) uncounted.push(label);
      // นับได้ไม่ครบทั้งรูปยังส่งรอบนี้ได้ ถ้าของที่นับได้พอกับจำนวนที่จะส่งรอบนี้ (ที่เหลือรอรอบถัดไป)
      else if (p.pack.status === "ไม่ครบ" && (p.pack.got ?? 0) < go)
        short.push(`${label} (นับได้ ${p.pack.got ?? 0} · รอบนี้ส่ง ${go})`);
      if (!it.noteAck) unread.add(it.name);
    });
  });
  if (sentOut.length) reasons.push(`รูปนี้ส่งครบไปแล้วในรอบก่อน: ${sentOut.join(", ")}`);
  if (over.length) reasons.push(`เลือกเกินจำนวนที่เหลือ: ${over.join(", ")}`);
  if (uncounted.length) reasons.push(`ตรวจนับรูปที่จะส่งก่อน: ${uncounted.join(", ")}`);
  if (short.length) reasons.push(`ของไม่พอกับจำนวนที่จะส่งรอบนี้: ${short.join(", ")}`);
  if (unread.size) reasons.push(`ยืนยันอ่านรายละเอียด: ${[...unread].join(", ")}`);
  if (!(order.packPhotos && order.packPhotos.length > 0)) reasons.push("ยังไม่ได้ถ่ายภาพก่อนปิดกล่อง");
  // เลือกครบทุกชิ้นที่เหลือ = รอบสุดท้าย ต้องยิงช่องเลขพัสดุปกติให้ใบปิด (สถานะจัดส่งแล้ว + ด่านเต็ม)
  const isLastRound = selQty > 0 && remaining > 0 && selQty >= remaining;
  // 🎁➗ ใบมัดจำที่ตั้งใจส่งตัวอย่างก่อน (ติ๊ก 🎁 + โฟลเดอร์ขึ้นตย) — รอบที่ไม่ใช่รอบสุดท้ายไม่ต้องรอครบ 100%
  const sampleInfo = isLastRound ? null : depositSampleRun(order);
  const sampleRun = sampleInfo?.ok === true;
  if (hasUnpaidBalance(order) && !sampleRun)
    reasons.push(
      order.deposit
        ? `ยังเก็บยอดคงเหลือ (มัดจำ 50%) ไม่ครบ${sampleInfo && sampleInfo.missing.length ? ` — ส่งตัวอย่างก่อนได้ถ้า: ${sampleInfo.missing.join(" · ")}` : ""}`
        : "ยังเก็บส่วนต่างที่ตีราคาเพิ่มไม่ครบ"
    );
  if (isLastRound) reasons.push("รอบนี้เอาของที่เหลือไปทั้งหมด = รอบสุดท้าย ให้ยิงที่ช่องเลขพัสดุด้านล่างแทน (ใบจะปิดเป็นจัดส่งแล้ว)");
  /**
   * 🚨 ของที่เหลือพร้อมส่งอยู่แล้ว + แอดมินไม่ได้สั่งแบ่งส่ง = เกือบทุกครั้งคือกดผิดทาง
   * เคสจริง 15 ก.ย. 69 (OD-260909-6151): ด่านทั้งใบล็อกที่ 🎁 งานตัวอย่าง คนแพ็คเลยอ้อมมาทางแบ่งส่ง
   * → ลูกค้าได้ไลน์ "จัดส่งบางส่วน · ที่เหลือส่งรอบหน้า" ทั้งที่ของไปครบในกล่องเดียว และใบไม่ปิด
   * ลูกค้าขอรับก่อนจริง ๆ = ให้แอดมินระบุแผนแบ่งส่ง (กติกาเจ้าของร้าน: ฝั่งแพ็คไม่ใช่คนตัดสินว่าจะแบ่ง)
   */
  const looksWhole = !isLastRound && selQty > 0 && !leftWaiting && leftReady.length > 0 && !(order.shipPlan?.length ?? 0);
  if (looksWhole)
    reasons.push(
      `${SPLIT_WHOLE_HINT} (${leftReady.join(" · ")}) — ถ้าของทั้งใบไปกล่องเดียว อย่าใช้แบ่งส่ง ให้ยิงเลขที่ช่องเลขพัสดุด้านล่างเพื่อปิดใบ · ถ้าลูกค้าขอรับก่อนจริง ให้แอดมินระบุแผนแบ่งส่งก่อน`
    );
  return { ready: reasons.length === 0, reasons, isLastRound, looksWhole };
}

export function packGate(order: Order): PackGate {
  const uncounted: PackGate["uncounted"] = [];
  const unread: string[] = [];
  const short: PackGate["short"] = [];
  const unsampled: string[] = [];

  // 🎁 ชิ้นงานตัวอย่างที่ส่งไปแล้วในรอบแบ่งส่งก่อนหน้า (ใบมัดจำส่งตัวอย่างก่อน) = ไม่ต้องใส่กล่องรอบสุดท้ายซ้ำ
  const sampleWentEarlier = (order.shipments?.length ?? 0) > 0 && !!order.deposit && depositSampleRun({ ...order, tracking: "" })?.ok === true;
  order.items.forEach((it) => {
    if (!it.noteAck) unread.push(it.name);
    if (it.sampleRequired && !it.samplePacked && !sampleWentEarlier) unsampled.push(it.name);
    proofsOf(it).forEach((p, j) => {
      if (!p.pack) uncounted.push({ item: it.name, index: j + 1 });
      else if (p.pack.status === "ไม่ครบ") short.push({ item: it.name, got: p.pack.got ?? 0, need: p.qty });
    });
  });

  const noPhoto = !(order.packPhotos && order.packPhotos.length > 0);
  const unpaidBalance = hasUnpaidBalance(order);
  const missing = packMissingOf(order);
  const taxInvoiceUnpacked = orderNeedsTaxInvoiceInBox(order) && !order.taxInvoicePacked;
  const planPending = pendingPlanRound(order);

  return {
    ready:
      !planPending &&
      !uncounted.length &&
      !unread.length &&
      !short.length &&
      !unsampled.length &&
      !noPhoto &&
      !unpaidBalance &&
      !missing.length &&
      !taxInvoiceUnpacked,
    uncounted,
    unread,
    short,
    unsampled,
    noPhoto,
    unpaidBalance,
    missing,
    taxInvoiceUnpacked,
    planPending,
  };
}

/** เหลืออีกกี่วันถึงวันใช้งาน (null = ไม่ได้ระบุ) · ติดลบ = เลยกำหนดแล้ว */
export function daysToUseBy(o: Order): number | null {
  if (!o.useByDate) return null;
  const d = new Date(o.useByDate + "T00:00:00");
  if (Number.isNaN(d.getTime())) return null;
  const today = new Date();
  today.setHours(0, 0, 0, 0);
  return Math.round((d.getTime() - today.getTime()) / 86400000);
}

/** เพิ่ม 1 บรรทัดลงประวัติออเดอร์ (คืน Order ใหม่ ไม่แก้ของเดิม) */
export function withLog(order: Order, by: string, action: string, detail?: string): Order {
  const entry: LogEntry = { at: new Date().toISOString(), by, action, ...(detail ? { detail } : {}) };
  return { ...order, log: [...(order.log ?? []), entry] };
}

