/** 🛒 ใบนี้ยังรอของเข้าอยู่ (ติ๊ก "ต้องสั่งของ" ไว้ และยังไม่มีใครกด "ของเข้าแล้ว") — ยังไม่ควรส่งเข้าผลิต */
export function orderAwaitingStock(o: Pick<Order, "needsPurchase">): boolean {
  return !!o.needsPurchase && !o.needsPurchase.arrivedAt;
}

/** 🧾 ใบนี้มีใบกำกับภาษี (สร้างจาก FlowAccount / แอดมินใส่ข้อมูลใบกำกับ / มี VAT ตามบิล) */
export function orderHasTaxInvoice(o: Order): boolean {
  return !!(o.flowAccount || o.taxInvoice || orderVatAmount(o) > 0);
}

/** 🧾 ต้องใส่ใบกำกับภาษีตัวจริงลงกล่อง (มีใบกำกับ และไม่ได้เลือกส่งทางอีเมล) */
export function orderNeedsTaxInvoiceInBox(o: Order): boolean {
  return orderHasTaxInvoice(o) && o.taxInvoiceDelivery !== "email";
}

/** 🧾 เลขที่ + ลิงก์เอกสารใบกำกับ — เอาจากข้อมูลใบกำกับก่อน (แอดมินวางลิงก์) ไม่มีค่อยใช้เอกสารต้นทาง FlowAccount */
export function taxInvoiceDocOf(o: Order): { docNo?: string; url?: string; label: string; company?: string } {
  const t = o.taxInvoice;
  const f = o.flowAccount;
  if (t?.docNo) return { docNo: t.docNo, url: t.docUrl, label: t.docTypeLabel ?? "เอกสาร", company: t.company };
  if (f) return { docNo: f.docNo, url: f.url, label: f.docTypeLabel, company: t?.company };
  return { label: "ใบกำกับภาษี", company: t?.company };
}

/** ราคาสินค้ารวม (ก่อนค่าส่ง/ส่วนลด) */
export function orderSubtotal(o: Order): number {
  return o.items.reduce((s, i) => s + i.qty * i.unitPrice, 0);
}

/** ส่วนลดของรายการนี้เป็นบาท (รองรับทั้งใส่บาทตรง ๆ และ % ของราคาบรรทัด) — ไม่เกินราคาบรรทัด */
export function itemDiscountAmount(i: OrderItem): number {
  const line = i.qty * i.unitPrice;
  if ((i.discountPct ?? 0) > 0) return Math.min(line, Math.floor((line * i.discountPct!) / 100));
  return Math.min(line, Math.max(0, i.discount ?? 0));
}

/** รวมส่วนลดรายรายการ (แอดมินใส่เอง) */
export function orderItemDiscounts(o: Order): number {
  return o.items.reduce((s, i) => s + itemDiscountAmount(i), 0);
}

/** ส่วนลดทั้งบิลของแอดมินเป็นบาท — % คิดจากยอดสินค้าหลังหักส่วนลดรายรายการ */
export function adminDiscountAmount(o: Order): number {
  const d = o.adminDiscount;
  if (!d) return 0;
  if ((d.pct ?? 0) > 0) {
    const base = Math.max(0, orderSubtotal(o) - orderItemDiscounts(o));
    return Math.floor((base * d.pct!) / 100);
  }
  return Math.max(0, d.amount ?? 0);
}

/**
 * สถานะส่วนลดโอนไวของออเดอร์ ณ เวลา now
 * none = ไม่มีส่วนลด · active = ยังอยู่ในเวลา (นับถอยหลัง) · locked = ได้แน่แล้ว (แจ้งโอนทัน / ใบเก่าไม่จำกัดเวลา) · expired = เลยเวลาโดยไม่แจ้งโอน
 * waived = แอดมินติ๊กเอาออกให้ (ลูกค้าไม่รับส่วนลด — โอนเต็มจำนวนมาแล้ว)
 */
export type EarlyPayState = "none" | "active" | "locked" | "expired" | "superseded" | "waived";

/** ส่วนลดอื่นของออเดอร์ (ระดับสมาชิก/คูปอง + ส่วนลดทั้งบิลจากแอดมิน + ส่วนลดรายรายการ) — ไม่รวมส่วนลดโอนไว */
export function orderOtherDiscounts(o: Order): number {
  return (o.discount?.amount ?? 0) + adminDiscountAmount(o) + orderItemDiscounts(o);
}

export function earlyPayState(o: Order, now: number = Date.now()): EarlyPayState {
  const e = o.earlyPay;
  if (!e || !(e.amount > 0)) return "none";
  // 🚫 ลูกค้าไม่รับส่วนลด (แอดมินติ๊กเอาออก) — ชนะทุกสถานะ รวมถึงใบที่ล็อก/จ่ายแล้ว เพราะเป็นการตกลงกับลูกค้าตรง ๆ
  if (e.waivedAt) return "waived";
  // ⚡ ไม่ใช้ร่วมกับส่วนลดอื่น (เจ้าของร้านสั่ง 10 ก.ย. 69 "มีส่วนลดอื่นแล้วไม่ต้องลดโอนไวอีก") — คิดสด
  // ⚠️ เฉพาะใบที่ยังไม่มีเงินเข้า — รับเงินแล้วห้ามเปลี่ยนส่วนลดย้อนหลัง (11 ก.ย. 69 OD-260909-5711: ลูกค้าโอน 3,177 ครบตามที่
  // ระบบบอกตอนนั้น (ลด 2% + โอนไว 10) แล้วกติกาใหม่ไปตัด 10 ทีหลัง → โชว์ค้าง ฿10 ทั้งที่จ่ายครบ) · แอดมินใส่ส่วนลดหลังรับเงิน
  // = ตั้งใจลดเพิ่ม (ยอดเกินโชว์เป็นชำระเกิน ให้แอดมินคืน/ปรับเอง) ไม่ใช่มาแทนโอนไว
  if (orderOtherDiscounts(o) > 0 && paidSoFar(o) <= 0) return "superseded";
  if (e.lockedAt || !e.expiresAt) return "locked";
  const t = Date.parse(e.expiresAt);
  if (!Number.isFinite(t)) return "locked";
  return now > t ? "expired" : "active";
}

/** เหลือเวลาแจ้งโอนอีกกี่มิลลิวินาที (0 = ไม่อยู่ในสถานะนับถอยหลัง) */
export function earlyPayMsLeft(o: Order, now: number = Date.now()): number {
  if (earlyPayState(o, now) !== "active") return 0;
  return Math.max(0, Date.parse(o.earlyPay!.expiresAt!) - now);
}

/**
 * 🔒 ล็อกส่วนลดโอนไว — เรียกตอนลูกค้าแจ้งโอน (slip-apply) หรือแอดมินยืนยันเงินเข้าเอง
 * ทันเวลา = ประทับ lockedAt · เลยเวลา/ไม่มีส่วนลด/ล็อกแล้ว = คืนออเดอร์เดิม (ส่วนลดหายไปตามกติกา)
 */
export function lockEarlyPay(o: Order, at: string, by: string): Order {
  if (earlyPayState(o, Date.parse(at) || Date.now()) !== "active") return o;
  return { ...o, earlyPay: { ...o.earlyPay!, lockedAt: at, lockedBy: by } };
}

/**
 * ⚡↩️ คืนส่วนลดโอนไวให้ใบที่ "หมดเวลา" ไปแล้ว — ล็อกย้อนหลังพร้อมเหตุผล
 *
 * ทางเข้า 3 ทาง (เจ้าของร้านสั่ง 16 ก.ย. 69 ให้ทำครบทั้งชุด):
 *   1) slip-apply: SlipOK อ่านเวลาโอนบนสลิปได้ และโอนทันเวลา (+ผ่อน graceMinutes) แต่แนบสลิปช้า
 *   2) slip-apply: โอนช้าจริง แต่โอนยอดที่ลดแล้วมาพอดี (ขาดเท่าส่วนลด) และเงินเข้าก่อนเริ่มผลิต → ยกให้ ไม่ทวง ฿5/฿10
 *   3) แอดมินกดปุ่ม "คืนส่วนลดโอนไว" ในหน้าออเดอร์ (SlipOK อ่านเวลาไม่ได้ · แนบแทนลูกค้า)
 * ทำงานเฉพาะสถานะ expired — ใบที่ล็อกแล้ว/ไม่รับส่วนลด/มีส่วนลดอื่น/ไม่มีส่วนลด คืนออเดอร์เดิม
 * ผลลัพธ์ = lockedAt ประทับด้วย "เวลาที่ใช้ตัดสิน" (เวลาโอนจริง หรือเวลาที่คืน) → earlyPayState เป็น locked ทุกจอเอง
 */
export function reinstateEarlyPay(o: Order, at: string, by: string): Order {
  if (earlyPayState(o) !== "expired") return o;
  return { ...o, earlyPay: { ...o.earlyPay!, lockedAt: at, lockedBy: by } };
}

/**
 * 🕰️ ลูกค้า "โอนทันเวลา" ไหม เมื่อรู้เวลาโอนจริงจากสลิป — เทียบกับ expiresAt + ผ่อน graceMinutes
 * ใช้กับใบที่หมดเวลาไปแล้ว (แนบสลิปช้า) · ไม่รู้เวลาโอน/ไม่มี expiresAt = false (ให้ทางอื่นตัดสิน)
 */
export function transferredInTime(o: Order, transAt: string | undefined, graceMinutes: number): boolean {
  const exp = o.earlyPay?.expiresAt;
  if (!exp || !transAt) return false;
  const t = Date.parse(transAt);
  const e = Date.parse(exp);
  if (!Number.isFinite(t) || !Number.isFinite(e)) return false;
  return t <= e + Math.max(0, graceMinutes) * 60_000;
}

/**
 * 🚫/↩️ ติ๊ก "ลูกค้าไม่รับส่วนลดโอนไว" (หรือติ๊กออกเพื่อคืนให้)
 * ลูกค้าบางคนโอนเต็มจำนวนมาเลย ไม่เอาส่วนลด — ยอดในเว็บที่ลดไว้จะกลายเป็น "ชำระเกิน ฿5/฿10" ค้างอยู่
 * ติ๊กเอาออก = ยอดรวม/ยอดค้าง/QR/ใบเสร็จ กลับเป็นราคาเต็มทุกหน้าจอเอง (ไม่ลบตัวเลขเดิมทิ้ง เผื่อคืนส่วนลด)
 */
export function setEarlyPayWaived(o: Order, waived: boolean, at: string, by: string): Order {
  if (!o.earlyPay) return o;
  const e = { ...o.earlyPay };
  if (waived) {
    e.waivedAt = at;
    e.waivedBy = by;
  } else {
    delete e.waivedAt;
    delete e.waivedBy;
  }
  return { ...o, earlyPay: e };
}

/** ส่วนลดโอนไวของออเดอร์นี้เป็นบาท (0 = ไม่ได้ลด หรือเลยเวลาแจ้งโอนแล้ว) */
export function orderEarlyPayAmount(o: Order, now?: number): number {
  const s = earlyPayState(o, now);
  return s === "active" || s === "locked" ? Math.max(0, o.earlyPay!.amount) : 0;
}

/** ส่วนลดทั้งหมดของออเดอร์ = คูปอง/ระดับ + ส่วนลดทั้งบิลจากแอดมิน + ส่วนลดรายรายการ + ส่วนลดโอนไว */
export function orderDiscountTotal(o: Order): number {
  return (o.discount?.amount ?? 0) + adminDiscountAmount(o) + orderItemDiscounts(o) + orderEarlyPayAmount(o);
}

/** VAT ตามบิล (บาท) — 0 = ออเดอร์ทั่วไปที่ราคารวมทุกอย่างแล้ว */
export function orderVatAmount(o: Order): number {
  return Math.max(0, o.vat?.amount ?? 0);
}

/** 🧾 ค่าบริการเพิ่มรวม (บาท) — ค่าตัดภาพ/ค่าส่งเพิ่ม/ค่าเร่งงาน ที่แอดมินเก็บทีหลัง (0 = ไม่มี) */
export function orderChargesTotal(o: Order): number {
  return (o.charges ?? []).reduce((s, c) => s + Math.max(0, Number(c.amount) || 0), 0);
}

export function orderTotal(o: Order): number {
  // ?? 0 กันออเดอร์เก่า/แถวที่ไม่มี shippingCost ทำให้ยอดกลายเป็น NaN แล้วลามไปทั้งระบบ
  // ปัดทศนิยม 2 ตำแหน่ง — ออเดอร์จาก FlowAccount มีสตางค์ (VAT 7%) ไม่ให้ลอยเป็น 1540.8000000001
  // ค่าบริการเพิ่ม (charges) บวกท้ายสุด — อยู่นอกฐานส่วนลด % (adminDiscountAmount คิดจาก subtotal สินค้า)
  return Math.max(
    0,
    Math.round((orderSubtotal(o) + (o.shippingCost ?? 0) - orderDiscountTotal(o) + orderVatAmount(o) + orderChargesTotal(o)) * 100) / 100
  );
}

/** ยอดหัก ณ ที่จ่ายของออเดอร์ (บาท) — 0 = ไม่ได้ตั้งหรือไม่หัก */
export function orderWhtAmount(o: Order): number {
  return Math.max(0, o.wht?.amount ?? 0);
}

/**
 * 📄 ยอด "ตามบิลที่ออกให้ลูกค้า" = ยอดรวมไม่นับค่าบริการเพิ่ม (charges)
 * charges คือเงินที่เก็บทีหลังนอกบิลที่ออกไปแล้ว (ค่าส่งตัวอย่าง/ค่าส่งเพิ่ม/ค่าตัดภาพ) — ใช้เทียบกับใบ FlowAccount
 * (OD-260914-7626 · 17 ก.ย. 69: ลูกค้าโอนค่าส่งตัวอย่าง ฿50 แยก — ต้องเก็บเพิ่มได้โดยบิล/VAT/หัก ณ ที่จ่ายไม่ขยับ และป้าย "ไม่ตรงใบ" ไม่ขึ้น)
 */
export function orderBilledTotal(o: Order): number {
  return Math.max(0, Math.round((orderTotal(o) - orderChargesTotal(o)) * 100) / 100);
}

/** ยอดโอนจริงหลังหัก ณ ที่จ่าย — ลูกค้านิติบุคคลโอนเท่านี้ ส่วนต่างตามใบ 50 ทวิ */
export function orderNetTransfer(o: Order): number {
  return Math.max(0, orderTotal(o) - orderWhtAmount(o));
}

/**
 * 💳 ยอดค้างของใบนี้ "คือหัก ณ ที่จ่ายทั้งก้อน" ใช่ไหม — ลูกค้าโอนถึงยอดสุทธิแล้ว ส่วนที่เหลือมาเป็นใบ 50 ทวิ ไม่ใช่เงินโอน
 * ใช้ตัดสินว่าจะนับ paidTotal เป็นยอดเต็มตามบิลได้ไหม (กติกา "นับว่าชำระครบ (หัก ณ ที่จ่าย)" ใน PATCH /api/admin/orders)
 *
 * ⚠️ ต้องเทียบว่ายอดค้าง ≈ ภาษีที่หัก ไม่ใช่แค่ "ค้างไม่เกินภาษีที่หัก" (OD-260914-7626 · 17 ก.ย. 69):
 * ใบที่นับชำระครบตามบิลไปแล้ว (paidTotal = ยอดบิล ไม่ใช่เงินเข้าจริง) พอยอดโตจริง ฿53.50 (แก้ค่าส่ง) ซึ่งน้อยกว่าภาษีที่หัก ฿334.50
 * กติกาเดิมมองว่า "โอนถึงยอดสุทธิแล้ว" เลยกลืนยอดเพิ่มทั้งก้อน — ลูกค้าหักภาษีทั้งก้อนหรือไม่หักเลย ยอดค้างที่เล็กกว่าภาษีมากจึงไม่ใช่ภาษี
 * เผื่อ: ลูกค้าปัดยอดโอนขึ้นไม่เกิน ฿5 · เศษสตางค์ ฿0.50
 */
export function whtCoversBalance(o: Order): boolean {
  const wht = orderWhtAmount(o);
  if (!(wht > 0) || o.paidTotal == null || !(paidSoFar(o) > 0)) return false;
  const gap = Math.round((orderTotal(o) - paidSoFar(o)) * 100) / 100;
  return gap > 0.5 && gap <= wht + 0.5 && gap >= wht - 5;
}

/**
 * 🧮 ฐานคิดภาษีของใบนี้ (ยอดก่อน VAT) = สินค้า + ค่าส่ง − ส่วนลด
 * ค่าบริการเพิ่ม (charges) ไม่อยู่ในฐาน — เก็บทีหลังนอกบิลที่ออกไปแล้ว (ดู orderTotal)
 */
export function orderTaxBase(o: Order): number {
  return Math.max(0, Math.round((orderSubtotal(o) + (o.shippingCost ?? 0) - orderDiscountTotal(o)) * 100) / 100);
}

/** ภาษีจากฐาน × เรต ปัด 2 ตำแหน่ง (ท่าเดียวกับที่ FlowAccount คิดในใบ) */
export function taxFromRate(base: number, rate: number): number {
  return Math.max(0, Math.round(base * rate) / 100);
}

/**
 * ⚠️ VAT / หัก ณ ที่จ่าย ที่เก็บไว้ ห่างจาก "เรต × ฐานล่าสุด" กี่บาท (บวก = ที่เก็บไว้น้อยกว่าที่ควรเป็น)
 * ไม่ 0 = ตัวเลขภาษีเป็นของฐานเก่า (แก้รายการ/ค่าส่ง/ส่วนลดทีหลังแล้วภาษีไม่ตาม) หรือแอดมินพิมพ์ทับเอง
 * → ยอดรวมของใบนี้ยังเชื่อไม่ได้ ห้ามเอาไปตัดสินว่าลูกค้าโอนขาด (ดู slip-apply)
 */
export function orderTaxDrift(o: Order): { vat: number; wht: number } {
  const base = orderTaxBase(o);
  const r2 = (n: number) => Math.round(n * 100) / 100;
  return {
    vat: o.vat?.rate ? r2(taxFromRate(base, o.vat.rate) - orderVatAmount(o)) : 0,
    wht: o.wht?.rate ? r2(taxFromRate(base, o.wht.rate) - orderWhtAmount(o)) : 0,
  };
}

/**
 * ยอดที่ใบนี้ "ควรจะเป็น" ถ้าคิด VAT/หัก ณ ที่จ่าย ตามเรตกับฐานล่าสุด — [ยอดรวม, ยอดโอนจริง]
 * ว่าง = ตัวเลขภาษีตรงเรตอยู่แล้ว (ยอดในระบบเชื่อได้) · ใช้ตอนตรวจสลิป: ลูกค้าโอนตรงยอดที่ถูกต้อง
 * แต่ในระบบเป็นอีกยอดหนึ่ง = ข้อมูลฝั่งเราผิด ไม่ใช่โอนขาด
 */
export function reconciledOrderAmounts(o: Order): number[] {
  const drift = orderTaxDrift(o);
  if (Math.abs(drift.vat) < 0.01 && Math.abs(drift.wht) < 0.01) return [];
  const r2 = (n: number) => Math.round(n * 100) / 100;
  const total = r2(orderTotal(o) + drift.vat);
  return [total, r2(total - (orderWhtAmount(o) + drift.wht))].filter((n) => n > 0);
}

/**
 * 🧾 คิด VAT/หัก ณ ที่จ่ายของใบนี้ใหม่ให้เป็น "เรต × ฐานล่าสุด" — ไม่ต้องมีใบก่อนหน้ามาเทียบ
 *
 * ต่างจาก reconcileOrderTax (ประตูเขียนออเดอร์) ที่ดูว่า "ฐานขยับจากใบเดิมไหม" แล้วกันเลขที่แอดมินพิมพ์เอง
 * ทางนี้ไม่มีใบเดิมให้เทียบ จึงห้ามเรียกลอย ๆ — ใช้เฉพาะตอนมี **หลักฐานจากภายนอก** ว่าตัวเลขเดิมเป็นของฐานเก่า
 * ปัจจุบันมีที่เดียว: สลิปที่ SlipOK ยืนยันแล้วว่าแท้ และยอดในสลิปตรงกับ "ยอดที่ควรจะเป็น" พอดี (ดู slip-apply.ts)
 * คืน null = ตัวเลขตรงเรตอยู่แล้ว ไม่มีอะไรให้แก้
 */
export function orderTaxToRate(o: Order): { order: Order; note: string } | null {
  const drift = orderTaxDrift(o);
  if (Math.abs(drift.vat) < 0.01 && Math.abs(drift.wht) < 0.01) return null;
  const base = orderTaxBase(o);
  const thb = (n: number) => n.toLocaleString("th-TH", { minimumFractionDigits: 2, maximumFractionDigits: 2 });
  const parts: string[] = [];
  let next = o;
  if (o.vat?.rate && Math.abs(drift.vat) >= 0.01) {
    const want = taxFromRate(base, o.vat.rate);
    parts.push(`VAT ${o.vat.rate}% ${thb(orderVatAmount(o))} → ${thb(want)}`);
    next = { ...next, vat: { ...o.vat, amount: want } };
  }
  if (o.wht?.rate && Math.abs(drift.wht) >= 0.01) {
    const want = taxFromRate(base, o.wht.rate);
    parts.push(`หัก ณ ที่จ่าย ${o.wht.rate}% ${thb(orderWhtAmount(o))} → ${thb(want)}`);
    next = { ...next, wht: { ...o.wht, amount: want } };
  }
  return parts.length ? { order: next, note: `ฐานภาษี ${thb(base)} บาท · ${parts.join(" · ")}` } : null;
}

/**
 * 🧾 คิด VAT/หัก ณ ที่จ่ายใหม่เมื่อ "ฐานภาษีขยับ" — กติกากลาง เรียกที่ประตูเขียนออเดอร์ที่เดียว
 *
 * ทำไมต้องมี (OD-260915-1705 · 15 ก.ย. 69): ใบเสนอราคา QT010660 แก้จำนวน 12 → 5 ชิ้น แอดมินกด
 * "ดึงรายการตามเอกสาร" รายการเปลี่ยนเป็น 1,520 แต่ VAT ยังค้าง 255.36 (7% ของ 3,648 ใบเก่า) และ
 * หัก ณ ที่จ่ายยังค้าง 109.44 → ยอดในระบบ 1,775.36 ไม่ตรงทั้งใบเก่าและใบใหม่ · ลูกค้าโอนสุทธิตามใบ
 * 1,580.80 ครบแล้ว แต่ระบบนับเป็น "รับบางส่วน" แล้วส่งไลน์ทวงอีก 194.56 บาท
 * (เคสเดียวกับ OD-260911-5435 คนละทางเข้า — ไล่อุดทีละทางเข้าไม่จบ จึงย้ายมาไว้ที่ประตูเขียน)
 *
 * แก้เฉพาะตัวเลขที่ "พิสูจน์ได้ว่าเป็นของฐานเก่า" คือ ผู้เรียกไม่ได้ส่งยอดใหม่มา + ยอดเดิมตรงเป๊ะกับ
 * เรต × ฐานเก่า → ยอดที่แอดมินพิมพ์ทับเอง (ตามใบ 50 ทวิของลูกค้า) หรือยอดที่ซิงก์มาจากเอกสารไม่โดนแตะ
 * คืน null = ไม่ต้องแก้อะไร
 */
export function reconcileOrderTax(prev: Order | null | undefined, next: Order): { order: Order; note: string } | null {
  if (!prev || (!next.vat?.rate && !next.wht?.rate)) return null;
  const before = orderTaxBase(prev);
  const after = orderTaxBase(next);
  if (Math.abs(before - after) < 0.01) return null; // ฐานไม่ขยับ = ภาษีไม่ต้องคิดใหม่
  const thb = (n: number) => n.toLocaleString("th-TH", { minimumFractionDigits: 2, maximumFractionDigits: 2 });
  const stale = (now: { rate: number; amount: number } | undefined, was: { rate: number; amount: number } | undefined): number | null => {
    if (!now?.rate || !was?.rate || now.rate !== was.rate) return null;
    if (Math.abs(now.amount - was.amount) >= 0.005) return null; // ผู้เรียกส่งยอดใหม่มาเอง = เชื่อตามนั้น
    if (Math.abs(now.amount - taxFromRate(before, now.rate)) >= 0.01) return null; // ไม่ใช่ยอดของฐานเก่า = แอดมินพิมพ์เอง อย่าไปยุ่ง
    const want = taxFromRate(after, now.rate);
    return Math.abs(want - now.amount) < 0.01 ? null : want;
  };
  const vat = stale(next.vat, prev.vat);
  const wht = stale(next.wht, prev.wht);
  if (vat == null && wht == null) return null;
  return {
    order: {
      ...next,
      ...(vat != null ? { vat: { ...next.vat!, amount: vat } } : {}),
      ...(wht != null ? { wht: { ...next.wht!, amount: wht } } : {}),
    },
    note:
      `ฐานภาษี ${thb(before)} → ${thb(after)} บาท` +
      (vat != null ? ` · VAT ${next.vat!.rate}% ${thb(next.vat!.amount)} → ${thb(vat)}` : "") +
      (wht != null ? ` · หัก ณ ที่จ่าย ${next.wht!.rate}% ${thb(next.wht!.amount)} → ${thb(wht)}` : ""),
  };
}

/**
 * 💵 เงินที่เข้าบัญชีจริงของใบนี้ที่แอดมินกรอกไว้ (0 = ยังไม่ได้กรอก → ถือว่าเข้าเท่ายอดโอนจริงตามบิล)
 * ใบเดียวจบเท่านั้น — ใบมัดจำโอนคนละงวด ยอดเข้าจริงของแต่ละงวดอ่านจากสลิปของงวดนั้น
 */
export function orderCashReceived(o: Order): number {
  const v = Number(o.cashReceived);
  return Number.isFinite(v) && v > 0 ? Math.round(v * 100) / 100 : 0;
}

/**
 * 💸 ค่าธรรมเนียมที่ธนาคารหักจากยอดโอน = ยอดโอนจริงตามบิล − เงินที่เข้าบัญชีจริง
 * 0 = ยังไม่ได้กรอกเงินเข้าจริง หรือเข้าครบ/เกิน (โอนเกินไม่ใช่ค่าธรรมเนียม)
 */
export function orderBankFee(o: Order): number {
  const got = orderCashReceived(o);
  if (got <= 0) return 0;
  return Math.max(0, Math.round((orderNetTransfer(o) - got) * 100) / 100);
}

/**
 * 📄 ยอด "รวมทั้งสิ้น" ตามใบ FlowAccount ของออเดอร์นี้ — null = ไม่ได้ผูกกับเอกสาร FlowAccount
 * ใบมัดจำเก็บ "มูลค่างานเต็ม" ไว้ในช่องนี้อยู่แล้ว (ดู api/admin/orders/flowaccount) จึงเทียบกับ orderTotal ได้ตรง ๆ
 */
export function flowAccountBillTotal(o: Order): number | null {
  const g = o.flowAccount?.grandTotal;
  return typeof g === "number" && g > 0 ? Math.round(g * 100) / 100 : null;
}

/**
 * ⚠️ ยอดในระบบเพี้ยนจากใบ FlowAccount ไปกี่บาท — บวก = ใบมากกว่าระบบ · 0 = ตรงกัน · null = ไม่ใช่ใบ FlowAccount
 *
 * ทำไมต้องมี (OD-260911-5435 · 11 ก.ย. 69): ออเดอร์สร้างจากลิงก์มาตรงบิล 4,823.56 แล้วแอดมินเปลี่ยนวิธีส่ง
 * เป็น "มารับเอง" → ค่าส่ง ฿100 ที่อยู่ในใบหายไปเงียบ ๆ (แล้วไล่แก้ส่วนลด/VAT/หัก ณ ที่จ่ายตามยอดใหม่)
 * ยอดในระบบเหลือ 4,718.70 แต่บิลจริงที่ลูกค้าถือยัง 4,823.56 · ลูกค้าโอนสุทธิตามใบ 4,688.32
 * SlipOK เทียบกับยอดในระบบเลยหาว่า "โอนขาด ฿30.38" แล้วส่งไลน์ทวงลูกค้าที่จ่ายครบแล้ว
 *
 * บิลจริงออกที่ FlowAccount — ยอดในระบบนี้ต้องตามใบทุกบาท ต่างเมื่อไหร่ = ข้อมูลฝั่งเราผิด ต้องเตือนให้แก้
 */
export function flowAccountGap(o: Order): number | null {
  const bill = flowAccountBillTotal(o);
  if (bill == null) return null;
  const gap = Math.round((bill - orderBilledTotal(o)) * 100) / 100;
  return Math.abs(gap) < 0.01 ? 0 : gap;
}

/**
 * ยอดที่ถือว่า "ลูกค้าโอนตรงตามใบ FlowAccount" ได้ — รวมทั้งสิ้น · สุทธิหลังหัก ณ ที่จ่าย · งวดมัดจำ (และสุทธิของงวดมัดจำ)
 * ใช้ตอนตรวจสลิป: สลิปที่ตรงกับใบแต่ไม่ตรงกับยอดในระบบ = ยอดในระบบผิด ไม่ใช่ลูกค้าโอนขาด
 */
export function flowAccountBillAmounts(o: Order): number[] {
  const fa = o.flowAccount;
  if (!fa) return [];
  const r2 = (n: number) => Math.round(n * 100) / 100;
  return [fa.grandTotal, fa.net, fa.deposit?.amount, fa.deposit?.net]
    .filter((n): n is number => typeof n === "number" && n > 0)
    .map(r2);
}

/** สลิปยอดนี้ตรงกับใบ FlowAccount ไหม (เผื่อเศษปัด ±1 บาท) — ใช้คู่กับ flowAccountGap */
export function slipMatchesFlowAccountBill(o: Order, slipAmount: number): boolean {
  if (!(slipAmount > 0)) return false;
  return flowAccountBillAmounts(o).some((n) => Math.abs(n - slipAmount) <= 1);
}

/**
 * ➗ ออเดอร์มัดจำ 50% ที่ลูกค้าหัก ณ ที่จ่าย — แบ่งยอดหักตามสัดส่วนของแต่ละงวด ให้ "โอนจริง" ต่องวดตรงกับใบของ FlowAccount
 * (11 ก.ย. 69 OD-260911-8026: ระบบโชว์งวดละ 10,973.12 แต่ใบยอดคงเหลือ BL002059 บอกยอดชำระ 10,665.46
 *  เพราะหัก 3% ของงวดนั้น 307.66 — ก่อนหน้านี้หน้าออเดอร์โชว์แต่ยอดหักทั้งใบ 615.32 กับยอดเต็ม เจ้าของร้านเลยเห็นว่าไม่ตรง)
 * first/second = ยอดงวด (รวม VAT) · firstWht/secondWht = หัก ณ ที่จ่ายของงวดนั้น · firstNet/secondNet = เงินที่ลูกค้าโอนจริง
 * ไม่มีหัก ณ ที่จ่าย → wht 0 และ net = ยอดงวด · ไม่ใช่ออเดอร์มัดจำ → null
 */
export function depositInstallments(
  o: Order
): { first: number; second: number; wht: number; firstWht: number; secondWht: number; firstNet: number; secondNet: number } | null {
  if (!o.deposit) return null;
  const r2 = (n: number) => Math.round(n * 100) / 100;
  const total = orderTotal(o);
  const first = r2(Math.min(total, Math.max(0, o.deposit.amount)));
  const second = r2(Math.max(0, total - first));
  const wht = orderWhtAmount(o);
  const firstWht = wht > 0 && total > 0 ? r2((wht * first) / total) : 0;
  const secondWht = r2(Math.max(0, wht - firstWht));
  return { first, second, wht, firstWht, secondWht, firstNet: r2(first - firstWht), secondNet: r2(second - secondWht) };
}

/** ยอดที่ลูกค้ายังค้างชำระ (มากกว่า 0 = ต้องโอนเพิ่ม เช่น หลังสั่งเพิ่มในออเดอร์เดิม) */
export function orderBalance(o: Order): number {
  return Math.max(0, orderTotal(o) - (o.paidTotal ?? 0));
}

/**
 * ลิงก์แชท LINE ของลูกค้าคนนี้ — ของใบนี้เอง หรือดึงจากออเดอร์เก่าของลูกค้าคนเดียวกัน
 * จับคู่จาก customerId ก่อน (แม่นสุด) ไม่มีค่อยใช้เบอร์โทร แล้วค่อยอีเมล
 * คืน source = "self" เมื่อเป็นของใบนี้ · "prev" เมื่อดึงมาจากใบก่อนหน้า (พนักงานไม่ต้องกรอกซ้ำ)
 */
export function lineChatOf(order: Order, all: Order[]): { url: string; source: "self" | "prev"; from?: string } | null {
  if (order.lineChatUrl) return { url: order.lineChatUrl, source: "self" };
  const phone = (order.phone ?? "").replace(/\D/g, "");
  const email = (order.email ?? "").trim().toLowerCase();
  const same = (o: Order) =>
    (order.customerId && o.customerId === order.customerId) ||
    (phone.length >= 8 && (o.phone ?? "").replace(/\D/g, "") === phone) ||
    (!!email && (o.email ?? "").trim().toLowerCase() === email);
  // ใบใหม่สุดที่มีลิงก์ = ห้องแชทล่าสุดที่พนักงานใช้จริง
  for (let i = all.length - 1; i >= 0; i--) {
    const o = all[i];
    if (o.id === order.id || !o.lineChatUrl || !same(o)) continue;
    return { url: o.lineChatUrl, source: "prev", from: o.id };
  }
  return null;
}

/** ลูกค้าคนเดียวกันไหม — customerId แม่นสุด ไม่มีค่อยใช้เบอร์/อีเมล */
function sameCustomer(a: Order, b: Order): boolean {
  const phone = (a.phone ?? "").replace(/\D/g, "");
  const email = (a.email ?? "").trim().toLowerCase();
  return (
    (!!a.customerId && b.customerId === a.customerId) ||
    (phone.length >= 8 && (b.phone ?? "").replace(/\D/g, "") === phone) ||
    (!!email && (b.email ?? "").trim().toLowerCase() === email)
  );
}

/**
 * LINE ของลูกค้าคนนี้ — ของใบนี้เอง หรือ "จำ" มาจากออเดอร์เก่าของลูกค้าคนเดียวกัน
 * ลูกค้าเก่าจึงไม่ต้องให้พนักงานผูกซ้ำทุกใบ (ระบบส่งข้อความได้เลย)
 */
export function lineUserOf(
  order: Order,
  all: Order[]
): { id: string; name?: string; picture?: string; source: "self" | "prev"; from?: string } | null {
  if (order.lineUserId)
    return { id: order.lineUserId, name: order.lineProfile?.name, picture: order.lineProfile?.picture, source: "self" };
  for (let i = all.length - 1; i >= 0; i--) {
    const o = all[i];
    if (o.id === order.id || !o.lineUserId || !sameCustomer(order, o)) continue;
    return { id: o.lineUserId, name: o.lineProfile?.name, picture: o.lineProfile?.picture, source: "prev", from: o.id };
  }
  return null;
}

/**
 * ออเดอร์ยังว่างเปล่า — เพิ่งกดสร้างจากหลังบ้าน ยังไม่ใส่ชื่อ/เบอร์/ที่อยู่/รายการเลย
 * ใช้ชะลอแถบแดง "บังคับผูก LINE" ไม่ให้ขึ้นตั้งแต่ยังไม่รู้ว่าลูกค้าคือใคร
 */
export function isBlankOrder(order: Order): boolean {
  const noName = !order.customer?.trim() || order.customer === "ยังไม่ระบุชื่อ";
  return (
    noName &&
    !(order.phone ?? "").trim() &&
    !(order.address ?? "").trim() &&
    !order.contactId &&
    !order.customerId &&
    order.items.length === 0
  );
}

/** รูปแบบงานของรายการ — รองรับออเดอร์เก่าที่เก็บเป็น proofUrl รูปเดียว */
/**
 * ป้ายด้านของภาพลายที่ลูกค้าแนบ — "ด้านหน้า" / "ด้านหลัง" · null = รายการนี้ไม่ได้แยกด้าน (งานด้านเดียว/ออเดอร์เก่า)
 * ใช้ติดใต้รูปในหน้าออเดอร์/ใบงาน/ใบเสนอราคา ให้กราฟฟิกรู้ว่าลายไหนพิมพ์ด้านไหนโดยไม่ต้องเดาจากลำดับ
 */
export function artworkSide(it: Pick<OrderItem, "artworkBackUrls">, url: string): "ด้านหน้า" | "ด้านหลัง" | null {
  const back = it.artworkBackUrls;
  if (!back?.length) return null;
  return back.includes(url) ? "ด้านหลัง" : "ด้านหน้า";
}

export function proofsOf(item: OrderItem): Proof[] {
  if (item.proofs?.length) return item.proofs;
  return item.proofUrl ? [{ url: item.proofUrl, at: item.proofUpdatedAt ?? "" }] : [];
}

/** รายการนี้ติ๊ก "ไม่ต้องทำแบบ" ไว้ (ยอดเพิ่ม/ค่าบริการ) — ดู OrderItem.noProof */
export function proofExempt(item: OrderItem): boolean {
  return !!item.noProof;
}

/**
 * รายการนี้ "ยังขาดแบบงาน" ที่ต้องมีคนทำ — ใช้แทน !proofsOf(it).length ทุกจอที่นับงานค้าง
 * รายการที่ติ๊กไม่ต้องทำแบบ = ไม่มีแบบก็ไม่ถือว่าขาด (แต่ถ้าแนบภาพมาแล้ว ก็เดินขั้นตอนตรวจแบบตามปกติ)
 */
export function proofMissing(item: OrderItem): boolean {
  return !proofsOf(item).length && !proofExempt(item);
}

/**
 * บรรทัดค่าธรรมเนียม/ยอดเพิ่ม ที่ไม่มีแบบงานโดยธรรมชาติ — ไม่ต้องรอให้ใครติ๊ก "ไม่ต้องทำแบบ"
 * · บรรทัด "🎨 Add on" ที่ระบบแตกให้ (productId ลงท้าย #…) · ชื่อขึ้นต้น "ค่า" (ค่าตัดภาพ · ค่าตัดแบ่ง+เย็บขอบ …)
 * วัดของจริง ก.ย. 69: 254 ใบ มี 18 ใบที่บรรทัดแบบนี้ไม่มีแบบและไม่ได้ติ๊ก noProof — ถ้านับเป็น "ขาดแบบ" ด่านปริ้นจะกันใบพวกนี้ทุกใบ
 */
export function isFeeLine(item: OrderItem): boolean {
  return (item.productId ?? "").includes("#") || /^\s*ค่า/.test(item.name ?? "");
}

/** รายการหนึ่งบรรทัดที่ยัง "ขวางการผลิต" — ดู proofBlockers */
export interface ProofBlocker {
  /** ลำดับในใบ (เริ่ม 0) · ของแถม = -1 */
  index: number;
  name: string;
  qty: number;
  /** missing = ยังไม่มีแบบ · waiting = ส่งแบบแล้วรอลูกค้าตรวจ · edit = ลูกค้าขอแก้ */
  why: "missing" | "waiting" | "edit";
}

const BLOCKER_WHY: Record<ProofBlocker["why"], string> = {
  missing: "ยังไม่มีแบบ",
  waiting: "รอลูกค้าตรวจแบบ",
  edit: "ลูกค้าขอแก้ไขแบบ",
};

/**
 * ⛔ รายการที่ยังขวางการผลิต = ต้องมีแบบ (ไม่ใช่ค่าธรรมเนียม/ไม่ได้ติ๊กไม่ต้องทำแบบ) แต่ยังไม่มีแบบ หรือมีแล้วลูกค้ายังไม่อนุมัติ
 * ใช้ 3 ด่านเดียวกัน: ลูกค้าอนุมัติแบบ (ออเดอร์ยังไม่เป็น "อนุมัติแบบ") · โยนโฟลเดอร์เข้าผลิต · ปริ้นใบงาน
 * ⚠️ ใบที่เข้าผลิตไปแล้ว/ผ่านมาแล้ว ไม่ถูกแตะย้อนหลัง — ด่านดูตอนลงมือทำเท่านั้น
 */
export function proofBlockers(order: Order): ProofBlocker[] {
  const out: ProofBlocker[] = [];
  order.items.forEach((it, index) => {
    const has = proofsOf(it).length > 0;
    if (!has) {
      if (proofExempt(it) || isFeeLine(it)) return;
      out.push({ index, name: it.name, qty: it.qty, why: "missing" });
    } else if (it.proofStatus !== "อนุมัติ") {
      out.push({ index, name: it.name, qty: it.qty, why: it.proofStatus === "ขอแก้ไข" ? "edit" : "waiting" });
    }
  });
  for (const g of order.gifts ?? []) {
    if ((g.proofs ?? []).length && g.proofStatus !== "อนุมัติ")
      out.push({ index: -1, name: `🎁 ${g.name}`, qty: g.qty ?? 0, why: g.proofStatus === "ขอแก้ไข" ? "edit" : "waiting" });
  }
  return out;
}

/**
 * ⛔🖨 ด่านปริ้นใบงาน/โยนโฟลเดอร์ = proofBlockers ยกเว้นใบมัดจำรอบตัวอย่างที่เจ้าของร้านอนุมัติแล้ว (sampleLabelOk)
 * — รอบตัวอย่างคือทำของจริงให้ลูกค้าดูก่อนอนุมัติ แบบยังไม่ผ่านเป็นเรื่องปกติของโฟลว์นั้น
 */
export function printBlockers(order: Order): ProofBlocker[] {
  return sampleLabelOk(order) ? [] : proofBlockers(order);
}

/** ข้อความสั้นต่อบรรทัด เช่น "รายการที่ 3 โฟโต้การ์ด ×12 — ยังไม่มีแบบ" */
export function proofBlockerLabel(b: ProofBlocker): string {
  return `${b.index >= 0 ? `รายการที่ ${b.index + 1} ` : ""}${b.name}${b.qty ? ` ×${b.qty}` : ""} — ${BLOCKER_WHY[b.why]}`;
}

/**
 * รายการนี้ "ลูกค้าจัดวางลายบนเทมเพลตเองมา" หรือเปล่า
 * ดูจากบรรทัดพิกัดของทีมผลิตที่จอวางลายแนบมาให้ (ออเดอร์ที่แนบไฟล์เฉย ๆ จะไม่มี)
 */
export function isSelfDesigned(item: OrderItem): boolean {
  return !!item.sel?.["ตำแหน่งลาย (ทีมผลิต)"];
}

/**
 * งานที่ "ลูกค้าจัดวางลายบนเทมเพลตเองมาแล้ว" ทุกรายการ และแบบผ่านการอนุมัติครบ
 * — ใช้ตัดสินว่าข้ามขั้นตอนทำแบบ/รอลูกค้าตรวจได้เลยไหม
 */
export function allSelfDesignedApproved(order: Order): boolean {
  if (!order.items.length) return false;
  return order.items.every((it) => {
    const proofs = proofsOf(it);
    // ยอดเพิ่ม/ค่าบริการที่ไม่ต้องทำแบบ = ไม่มีอะไรให้ตรวจ ถือว่าผ่าน
    if (!proofs.length && proofExempt(it)) return true;
    if (!proofs.length) return false;
    // แบบชุดนี้ต้องมาจากจอวางลายของลูกค้า และอนุมัติครบทุกรูป
    return isSelfDesigned(it) && proofs.every((p) => p.review === "อนุมัติ");
  });
}

/**
 * รายการที่กราฟฟิก "ต้องลงมือทำ" ในออเดอร์นี้
 * = ลูกค้าไม่ได้จัดวางเอง และ (ยังไม่มีแบบ หรือ ลูกค้าขอแก้)
 */
export function graphicTodoItems(order: Order): OrderItem[] {
  return order.items.filter((it) => {
    if (isSelfDesigned(it)) return false; // ลูกค้าทำมาแล้ว กราฟฟิกไม่ต้องแตะ
    return proofMissing(it) || it.proofStatus === "ขอแก้ไข";
  });
}

/** รายการที่ส่งแบบให้ลูกค้าแล้ว กำลังรอลูกค้ากดตรวจ */
export function graphicWaitingItems(order: Order): OrderItem[] {
  return order.items.filter(
    (it) => !isSelfDesigned(it) && proofsOf(it).length > 0 && it.proofStatus !== "ขอแก้ไข" && it.proofStatus !== "อนุมัติ",
  );
}

/**
 * สถานะที่ควรเป็น "หลังเงินเข้าครบ"
 * งานที่ลูกค้าออกแบบเองมาแล้วไม่ต้องรอทำแบบ/รอตรวจ → ข้ามไป "อนุมัติแบบ" เลย
 */
export function paidStatusFor(order: Order): OrderStatus {
  return allSelfDesignedApproved(order) ? "อนุมัติแบบ" : "ชำระแล้ว";
}

