/** ขนาดกรอบเส้นตัดของทรงมาตรฐาน (มม.) */
export const SLEEVE_STD = { w: STD.w, h: STD.h };
/** ช่วงปลายที่คงรูป (มม. ของทรงมาตรฐาน) — ซ้าย = ลิ้นล็อก + ขอบเอียง · ขวา = รอยกรีด + ขอบเอียง */
const END_L = 27;
const END_R = 47;

export interface SleeveDieline {
  /** มม. นับจากมุมซ้ายบนของกรอบเส้นตัด */
  cut: CutCurve[];
  slits: CutCurve[];
  bleed: CutCurve[];
  w: number;
  h: number;
  /** อัตราย่อขยายตามความสูง (เทียบมาตรฐาน) */
  k: number;
}

/** เส้นไดคัทปลอกแก้วกรอบ wMm × hMm (กว้าง = ด้านยาวสุดตอนกางแบน) */
export function sleeveDieline(wMm: number, hMm: number): SleeveDieline {
  const k = hMm / STD.h;
  const W0 = STD.w * k;
  const eL = END_L * k;
  const eR = END_R * k;
  const mid0 = W0 - eL - eR;
  const midT = wMm - eL - eR;
  const fx =
    midT >= wMm * 0.15
      ? (x: number) => (x <= eL ? x : x >= W0 - eR ? x + (wMm - W0) : eL + (x - eL) * (midT / mid0))
      : (x: number) => x * (wMm / W0);
  const P = (x: number, y: number) => ({ x: fx(x * k), y: y * k });
  const conv = (r: Raw): CutCurve => ({
    start: P(r.s[0], r.s[1]),
    segs: r.g.map((g) => ({ c1: P(g[0], g[1]), c2: P(g[2], g[3]), to: P(g[4], g[5]) })),
  });
  return { cut: [conv(STD.cut)], slits: STD.slits.map(conv), bleed: [conv(STD.bleed)], w: wMm, h: hMm, k };
}

/** ตัดตกรอบผืน (มม.) ให้คลุมขอบตัดตกของทรงที่ขยายแล้ว */
export const sleeveBleedMm = (hMm: number) => Math.max(5, Math.ceil(4 * (hMm / STD.h)) + 1);

/** เพิ่มเส้น (มม. + เลื่อน off) ลง path ของ canvas ที่สเกล k พิกเซล/มม. · open = ไม่ปิดเส้น (รอยกรีด) */
export function dieCurvesPath(ctx: CanvasRenderingContext2D, cs: CutCurve[], k: number, off: number, open = false) {
  for (const c of cs) {
    ctx.moveTo((c.start.x + off) * k, (c.start.y + off) * k);
    for (const s of c.segs) ctx.bezierCurveTo((s.c1.x + off) * k, (s.c1.y + off) * k, (s.c2.x + off) * k, (s.c2.y + off) * k, (s.to.x + off) * k, (s.to.y + off) * k);
    if (!open) ctx.closePath();
  }
}

/** svg path d (มม. + เลื่อน off) — เส้นตัดปิด + รอยกรีดเปิด (ไฟล์ .pdf ผลิต) */
export function dieSvgD(d: { cut: CutCurve[]; slits: CutCurve[] }, off: number): string {
  const n = (v: number) => (Math.round((v + off) * 1000) / 1000).toString();
  const one = (c: CutCurve, close: boolean) =>
    `M ${n(c.start.x)} ${n(c.start.y)} ` + c.segs.map((s) => `C ${n(s.c1.x)} ${n(s.c1.y)} ${n(s.c2.x)} ${n(s.c2.y)} ${n(s.to.x)} ${n(s.to.y)}`).join(" ") + (close ? " Z" : "");
  return [...d.cut.map((c) => one(c, true)), ...d.slits.map((c) => one(c, false))].join(" ");
}

/** เส้นแบบ AiPath ของ lib/calendar-ai (มม. + เลื่อน off) */
export function dieAiCurves(cs: CutCurve[], off: number, open = false) {
  return cs.map((c) => ({
    s: [c.start.x + off, c.start.y + off] as [number, number],
    g: c.segs.map((s) => [s.c1.x + off, s.c1.y + off, s.c2.x + off, s.c2.y + off, s.to.x + off, s.to.y + off] as [number, number, number, number, number, number]),
    ...(open ? { open: true } : {}),
  }));
}
