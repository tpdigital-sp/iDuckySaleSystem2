/**
 * ออเดอร์เก่า/ใบเสนอราคาเก็บตัวเลือกเป็นข้อความรวมคั่นด้วย " · " — กางกลับเป็นคู่ หัวข้อ/ค่า
 * ค่าบางตัวมี " · " อยู่ข้างใน (เช่น "เรทราคา: พรีเมี่ยม · สกรีน 2 ด้าน") → ท่อนที่ไม่มีหัวข้อ
 * ให้ต่อท้ายค่าของหัวข้อก่อนหน้า ไม่ตัดเป็นบรรทัดใหม่
 * (แยกออกจาก SpecLines.tsx เพื่อให้ lib/สคริปต์ฝั่งเซิร์ฟเวอร์ใช้ได้โดยไม่ต้องลากคอมโพเนนต์มา)
 */
export function parseSpecText(text: string): [string, string][] {
  const out: [string, string][] = [];
  // ขึ้นบรรทัดใหม่ = คนละหัวข้อเสมอ (ข้อความที่แอดมินพิมพ์เองในใบเสนอราคา/ออเดอร์เก่า)
  for (const line of text.split(/\n+/)) {
    const segs = line
      .split(/\s·\s/)
      .map((s) => s.trim())
      .filter(Boolean);
    let head = -1; // ตำแหน่งหัวข้อล่าสุดของบรรทัดนี้ — ท่อนที่ไม่มีหัวข้อไปต่อท้ายตัวนี้
    for (const seg of segs) {
      const m = seg.match(/^([^:]{1,60}?):\s*(.+)$/);
      // กัน "https://..." ถูกอ่านว่าเป็นหัวข้อ (มี : เหมือนกัน)
      const isLabel = m && !/^\s*https?$/i.test(m[1]);
      if (isLabel && m) {
        out.push([m[1].trim(), m[2].trim()]);
        head = out.length - 1;
      } else if (head >= 0) {
        out[head][1] += ` · ${seg}`;
      } else {
        out.push(["", seg]);
      }
    }
  }
  return out;
}

/** 1 ตร.ม. ของงานสติ๊กเกอร์ = 8 แผ่น A3 (ตัวคูณเดียวกับ sheetYield.unitSheets ของ sticker-uv) */
const SQM_A3_NOTE = "1 ตร.ม. = 8 A3";

/**
 * 🏷 ชื่อหัวข้อที่โชว์บนจอ — ตัดส่วนขยายที่บอกว่า "กลุ่มนี้เป็นของตะขอแบบไหน" ออก (เจ้าของร้านสั่ง 15 ก.ย. 69)
 *
 * กลุ่มสีตะขอมีหลายกลุ่มในสินค้าเดียว แยกกันด้วยรหัสตะขอท้ายชื่อ ("สีตะขอ · เงิน/ทอง (D/X)" ·
 * "สีตะขอ · โลหะ (F/J/K/L/M/N/O)" · "สีตะขอ R (โลหะ)") ไว้ให้ตอนตั้งค่าสินค้าเลือกไม่ผิดกลุ่ม
 * แต่บนใบงาน/ออเดอร์เหลือให้เห็นแค่กลุ่มเดียว (กลุ่มของตะขอที่ลูกค้าเลือก) และบรรทัด "ตะขอ:" อยู่เหนือขึ้นไปแล้ว
 * รหัสท้ายชื่อจึงเป็นแค่บรรทัดรก — โชว์ "สีตะขอ" เฉย ๆ
 *
 * ตัดเฉพาะส่วนขยายที่แยกด้วยตัวคั่น (" · " หรือเว้นวรรคแล้วขึ้นด้วยรหัสอังกฤษ) — ชื่อที่ติดกันเป็นคำเดียว
 * ("สีตะขอโซ่ไข่ปลา" · "สีตะขอแขวน") เป็นชื่อของอะไหล่คนละตัว ห้ามตัด
 *
 * 📐 "ขนาดตัด (ตร.ม.)" → "ขนาดตัด (1 ตร.ม. = 8 A3)" (กราฟฟิกขอ 17 ก.ย. 69 · OD-260914-7004)
 * งานเรทตารางเมตรของสติ๊กเกอร์ UV — กราฟฟิกต้องรู้ว่า 1 ตร.ม. วางได้กี่แผ่น A3 ตอนจัดไฟล์ (ใบงานเดิมเขียนกำกับไว้เอง)
 * มีสินค้าเดียวที่ใช้หัวข้อนี้ (sticker-uv · A3 = 8 ชิ้น/ตร.ม. · sheetYield.unitSheets["ตร.ม."] = 8) จึงเขียนเลข 8 ตรงนี้ได้
 * งานกำหนดขนาดเองไม่มีบรรทัด "ขนาดตัด (ตร.ม.)" — ห้อยไว้ที่บรรทัดกว้างแทน ("ขนาดตัด ตร.ม. (กว้าง)")
 *
 * ⚠️ แสดงผลอย่างเดียว — คีย์ที่เก็บในออเดอร์/ตารางราคา/ค่าเพิ่มต่อชิ้น (extras) ยังเป็นชื่อกลุ่มเต็มเหมือนเดิม
 */
export function specLabel(k: string): string {
  return k
    .replace(/^(สีตะขอ)(?:\s*·\s*\S.*| +[A-Za-z].*)$/u, "$1")
    .replace(/^ขนาดตัด\s*\(ตร\.ม\.\)$/u, `ขนาดตัด (${SQM_A3_NOTE})`)
    .replace(/^ขนาดตัด\s*ตร\.ม\.\s*\(กว้าง\)$/u, `ขนาดตัด กว้าง (${SQM_A3_NOTE})`);
}

