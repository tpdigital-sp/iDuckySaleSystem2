    return "จงอ่านเนื้อหาทั้งหมดจากภาพที่แนบมา (รวมถึงข้อความ ชื่อสินค้า รายละเอียด ราคา ฯลฯ) แล้วเรียบเรียงให้เป็นระเบียบในรูปแบบ Markdown หัวข้อชัดเจน อ่านง่ายสำหรับแอดมินมืออาชีพ ห้ามเพิ่มข้อมูลที่ไม่มีในภาพ";
