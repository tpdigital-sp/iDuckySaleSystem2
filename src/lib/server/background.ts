import { after } from "next/server";

/**
 * 🧊 งานเบื้องหลัง "หลังตอบแล้ว" — ยิงไลน์ · ตัดสต๊อก · แต้มสะสม · ซิงก์ TP · ยอดขายแล้ว
 *
 * ห้ามเขียน `void task()` เฉย ๆ ในโค้ดที่รันบน Netlify: ฟังก์ชัน (AWS Lambda) ถูก "แช่แข็ง" ทันทีที่ส่งคำตอบ
 * งานที่ยังไม่เสร็จค้างอยู่กลางอากาศ แล้วไปตื่นต่อในคำขอถัดไป (15 วิ–หลายนาทีให้หลัง) — นาฬิกา timeout
 * 10 วิของ fetch หมดไปแล้ว → ล้มทันทีที่ตื่น · ถ้าเครื่องถูกทิ้งไปเลยก็หายเงียบ ไม่มีแม้แต่ประวัติ
 *
 * หลักฐาน 25 ก.ย. 69 (ประวัติออเดอร์ 14 วัน): ไลน์ที่ส่งถึง log ห่างจากเหตุ 3–5 วิ · ที่ขึ้น "ต่อ LINE ไม่ได้"
 * ห่าง 15–75 วิ (กลาง 26 วิ) ไม่มีสักใบใกล้ 10 วิ = ไม่ใช่เน็ตช้า แต่ถูกแช่แข็งแล้วค่อยตื่นมาล้ม
 *
 * after() ของ Next บอกแพลตฟอร์มให้ "รอจนงานเสร็จค่อยพัก" (Netlify Next runtime ≥ 5.9 รองรับผ่าน waitUntil)
 * · งานเริ่มทันที (ไม่รอคำตอบ) แค่ไม่ถูกทิ้ง · เรียกนอก request scope (สคริปต์/เทส/cron ที่เรียกตรง) = after() throw
 * → ปล่อยวิ่งตามปกติ (process ธรรมดาไม่แช่แข็งอยู่แล้ว)
 */
export function inBackground(label: string, task: Promise<unknown>): void {
  const settled = task.then(
    () => undefined,
    (e: unknown) => console.error(`[background] ${label} ล้ม:`, e instanceof Error ? `${e.name}: ${e.message}` : e)
  );
  try {
    after(() => settled);
  } catch {
    /* นอก request scope — ไม่มีใครแช่แข็ง ปล่อยวิ่งไป */
  }
}
